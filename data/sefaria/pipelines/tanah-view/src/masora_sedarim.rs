/// The extracted sedarim reference list (fixture file).
#[derive(Debug, Deserialize)]
pub struct SedarimReference {
    pub provenance: SedarimProvenance,
    pub groups: Vec<SedarimGroup>,
}

#[derive(Debug, Deserialize)]
pub struct SedarimProvenance {
    pub title: String,
    pub source_url: String,
    pub retrieved: String,
    pub sha256: String,
    pub bytes: u64,
    pub pages: u32,
    pub notes: Vec<String>,
}

#[derive(Debug, Deserialize)]
pub struct SedarimGroup {
    /// The sefer (or grouped sefer) as printed in the PDF, e.g.
    /// "שמואל", "תרי עשר", "עזרא נחמיה".
    pub book: String,
    pub sedarim: Vec<SedarEntry>,
}

/// One printed sedarim-table entry — the seder's first pasuk.
#[derive(Debug, Deserialize)]
pub struct SedarEntry {
    /// Seder number in Hebrew letters as printed (parenthesized for
    /// manuscript-only entries).
    pub seder: String,
    /// True when the PDF wraps the number in parentheses — a boundary
    /// attested only in some ancient manuscripts.
    #[serde(default)]
    pub paren: bool,
    /// Sub-sefer label for grouped books: "א"/"ב" for שמואל, מלכים,
    /// דברי הימים; the member-sefer name inside תרי עשר; עזרא/נחמיה
    /// inside עזרא נחמיה. None for single sefarim.
    #[serde(default)]
    pub sub_book: Option<String>,
    /// Perek and pasuk in Hebrew letters, as printed.
    pub perek: String,
    pub pasuk: String,
    /// The same coordinates as numbers (verified against the letters
    /// by the integrity checks).
    pub perek_n: i32,
    pub pasuk_n: i32,
}

/// How a listed seder head aligns with the ptuha/stuma-derived
/// parasha it maps onto. The three non-aligned classes mirror the
/// documented masoretic phenomenon: seder heads are set at a
/// parasha's start, at its last pasuk, or inside it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind")]
pub enum SederAlignment {
    /// The head pasuk opens a corpus unit (parasha boundary).
    #[serde(rename = "parasha-boundary")]
    ParashaBoundary,
    /// The corpus splits the head pasuk itself — the boundary sits
    /// inside the seder's first verse at `segment_index`.
    #[serde(rename = "mid-pasuk-boundary")]
    MidPasukBoundary { segment_index: i32 },
    /// The head pasuk is the last pasuk of a corpus parasha; the
    /// parasha break follows the seder's first verse.
    #[serde(rename = "parasha-last-pasuk")]
    ParashaLastPasuk { closing_break: String },
    /// The head pasuk sits strictly inside a corpus parasha.
    #[serde(rename = "interior-of-parasha")]
    InteriorOfParasha,
    /// The entry could not be resolved inside the corpus.
    #[serde(rename = "unresolved")]
    Unresolved { reason: String },
}

/// Adjudication status for a verified entry.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind")]
pub enum Disposition {
    /// The corpus already carries a boundary at the seder head.
    #[serde(rename = "aligned")]
    Aligned,
    /// Literature-documented mid-parasha seder head — an expected
    /// difference between the two Masoretic systems.
    #[serde(rename = "documented-system-difference")]
    DocumentedSystemDifference,
    /// Manuscript-only (parenthesized) boundary; alignment with
    /// ptuha/stuma markers is incidental.
    #[serde(rename = "manuscript-only")]
    ManuscriptOnly,
    /// The corpus parasha shape differs from the edition documented
    /// for this seder head — possible corpus/edition divergence that
    /// needs a second parasha source to resolve.
    #[serde(rename = "edition-divergence")]
    EditionDivergence { detail: String },
    /// Consistent with the documented two-system divergence; needs
    /// adjudication only if the product adopts the seder division.
    #[serde(rename = "needs-adjudication")]
    NeedsAdjudication,
}

/// One reference entry resolved and classified against the corpus.
#[derive(Debug, Serialize, Deserialize, PartialEq)]
pub struct VerifiedSeder {
    pub book: String,
    pub seder: String,
    pub paren: bool,
    /// Rendered canonical reference, e.g. "שמואל א ג כ".
    pub reference: String,
    pub perek_id: i32,
    pub pasuk: i32,
    pub alignment: SederAlignment,
    pub disposition: Disposition,
    /// The corpus unit covering the head pasuk (evidence).
    pub unit_id: i32,
    pub unit_heading: String,
    pub unit_closing_break: Option<String>,
    /// The containing sefer has no ptuha/stuma markers at all, so any
    /// interior classification there is degenerate rather than real
    /// evidence about the seder head's placement.
    #[serde(default)]
    pub marker_free_sefer: bool,
}

