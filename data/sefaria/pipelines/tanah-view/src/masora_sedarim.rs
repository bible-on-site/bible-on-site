/// Map a PDF book label to the corpus sefer name.
fn corpus_sefer_name(book: &str) -> &str {
    match book {
        // The PDF prints the common spelling; the corpus uses the
        // plene spelling.
        "תהלים" => "תהילים",
        // The corpus keeps עזרא and נחמיה as additionals of one sefer.
        "עזרא נחמיה" => "עזרא",
        other => other,
    }
}

/// One contiguous perakim part of a sefer — the sefer itself or one
/// additional — with its display name for references.
struct ResolvedPart<'a> {
    display: &'a str,
    /// Index of the owning sefer in the corpus, for sefer-level
    /// metadata such as marker-free detection.
    sefer_idx: usize,
    perek_from: i32,
    perakim: &'a [Perek],
}

/// Resolve a reference (book, sub-book) to its corpus perakim part.
fn resolve_part<'a>(
    sefarim: &'a [Sefer],
    book: &str,
    sub_book: Option<&str>,
) -> Result<ResolvedPart<'a>> {
    if book == "תרי עשר" {
        let member = sub_book.context("תרי עשר entry is missing its member sefer")?;
        let sefer = sefarim
            .iter()
            .find(|s| s.name == member)
            .with_context(|| format!("Unknown תרי עשר member sefer {member}"))?;
        return sefer_as_part(sefarim, sefer, book);
    }
    let sefer_name = corpus_sefer_name(book);
    let (sefer_idx, sefer) = sefarim
        .iter()
        .enumerate()
        .find(|(_, s)| s.name == sefer_name)
        .with_context(|| format!("Reference book {book} has no corpus sefer"))?;
    match &sefer.additionals {
        None => {
            if let Some(sub) = sub_book {
                bail!("{book} has no additionals but entry names sub-book {sub}");
            }
            sefer_as_part(sefarim, sefer, book)
        }
        Some(additionals) => {
            let sub =
                sub_book.with_context(|| format!("{book} entry is missing its sub-book label"))?;
            let additional = additionals
                .iter()
                .find(|a| a.letter == sub || a.name == sub)
                .with_context(|| format!("{book} has no additional {sub}"))?;
            Ok(ResolvedPart {
                display: additional.name.as_str(),
                sefer_idx,
                perek_from: additional.perek_from,
                perakim: &additional.perakim,
            })
        }
    }
}

fn sefer_as_part<'a>(
    sefarim: &'a [Sefer],
    sefer: &'a Sefer,
    book: &str,
) -> Result<ResolvedPart<'a>> {
    let sefer_idx = sefarim
        .iter()
        .position(|s| std::ptr::eq(s, sefer))
        .context("sefer not found in corpus")?;
    let perakim = sefer.perakim.as_ref().with_context(|| {
        format!(
            "{book}: sefer {} has neither perakim nor additionals",
            sefer.name
        )
    })?;
    Ok(ResolvedPart {
        display: sefer.name.as_str(),
        sefer_idx,
        perek_from: sefer.perek_from,
        perakim,
    })
}

/// A resolved seder head coordinate.
struct ResolvedHead<'a> {
    /// The containing part's first perek id — the book's start for
    /// the first-seder coverage check.
    part_perek_from: i32,
    /// Owning sefer index — lets the report flag marker-free sefarim
    /// whose interior classifications are degenerate.
    sefer_idx: usize,
    perek_id: i32,
    pasuk: i32,
    perek: &'a Perek,
}

fn resolve_head<'a>(
    part: &ResolvedPart<'a>,
    entry: &SedarEntry,
    book: &str,
) -> Result<ResolvedHead<'a>> {
    let perek_idx = entry.perek_n - 1;
    if perek_idx < 0 || perek_idx as usize >= part.perakim.len() {
        bail!(
            "{book} {} {}: perek {} is outside {} ({} perakim)",
            entry.seder,
            entry.sub_book.as_deref().unwrap_or_default(),
            entry.perek,
            part.display,
            part.perakim.len()
        );
    }
    let perek = &part.perakim[perek_idx as usize];
    if entry.pasuk_n < 1 || entry.pasuk_n as usize > perek.pesukim.len() {
        bail!(
            "{book} {} {} {}: pasuk {} is outside {} ({} pesukim)",
            entry.seder,
            entry.perek,
            entry.pasuk,
            entry.pasuk_n,
            part.display,
            perek.pesukim.len()
        );
    }
    Ok(ResolvedHead {
        part_perek_from: part.perek_from,
        sefer_idx: part.sefer_idx,
        perek_id: part.perek_from + perek_idx,
        pasuk: entry.pasuk_n,
        perek,
    })
}

/// Does a unit's span cover the given (perek_id, pasuk)? Seder heads
/// are whole-pasuk positions, so segment indices do not matter for
/// containment.
fn unit_covers_pasuk(unit: &ReadingUnit, perek_id: i32, pasuk: i32) -> bool {
    let range = &unit.ranges[0];
    let after_start = perek_id > range.start.perek_id
        || (perek_id == range.start.perek_id && pasuk >= range.start.pasuk);
    let before_end = perek_id < range.end.perek_id
        || (perek_id == range.end.perek_id && pasuk <= range.end.pasuk);
    after_start && before_end
}

/// The coordinate that should open the unit following a marker-closed
/// end — an independent re-derivation of the contract used by the
/// tiling check (mirrors `coordinateAfterMarker` semantics).
fn coordinate_after_end(sefarim: &[Sefer], end: &Coordinate) -> Result<Option<Coordinate>> {
    let marker_index = end
        .segment_index
        .context("tiling check expects marker-closed ends to carry a segment index")?;
    let (sefer_idx, (perek_from, _perek_to, perakim)) = locate_perek(sefarim, end.perek_id)?;
    let sefer = &sefarim[sefer_idx];
    let perek_idx = (end.perek_id - perek_from) as usize;
    let perek = perakim
        .get(perek_idx)
        .context("perek id outside its part")?;
    let pasuk = perek
        .pesukim
        .get(end.pasuk as usize - 1)
        .context("end pasuk outside its perek")?;
    if marker_index as usize + 1 < pasuk.segments.len() {
        return Ok(Some(Coordinate {
            perek_id: end.perek_id,
            pasuk: end.pasuk,
            segment_index: Some(marker_index + 1),
        }));
    }
    if (end.pasuk as usize) < perek.pesukim.len() {
        return Ok(Some(Coordinate {
            perek_id: end.perek_id,
            pasuk: end.pasuk + 1,
            segment_index: None,
        }));
    }
    // End of perek: the next unit opens the next perek within the same
    // part, the next additional's first perek, or nothing (sefer end).
    let parts = sefer_parts(sefer);
    let part_idx = parts
        .iter()
        .position(|(pf, _, _)| *pf == perek_from)
        .context("locate_perek returned a part that is not in the sefer")?;
    if perek_idx + 1 < perakim.len() {
        return Ok(Some(Coordinate {
            perek_id: end.perek_id + 1,
            pasuk: 1,
            segment_index: None,
        }));
    }
    if part_idx + 1 < parts.len() {
        return Ok(Some(Coordinate {
            perek_id: parts[part_idx + 1].0,
            pasuk: 1,
            segment_index: None,
        }));
    }
    Ok(None)
}

/// (perek_from, perek_to, perakim) for one contiguous part of a sefer.
type SeferPart<'a> = (i32, i32, &'a [Perek]);

fn sefer_parts(sefer: &Sefer) -> Vec<SeferPart<'_>> {
    if let Some(perakim) = &sefer.perakim {
        return vec![(sefer.perek_from, sefer.perek_to, perakim.as_slice())];
    }
    sefer
        .additionals
        .as_ref()
        .map(|additionals| {
            additionals
                .iter()
                .map(|a| (a.perek_from, a.perek_to, a.perakim.as_slice()))
                .collect()
        })
        .unwrap_or_default()
}

/// Locate a canonical perek id: returns the sefer index and the
/// containing part's (perek_from, perek_to, perakim).
fn locate_perek<'a>(sefarim: &'a [Sefer], perek_id: i32) -> Result<(usize, SeferPart<'a>)> {
    for (si, sefer) in sefarim.iter().enumerate() {
        for part in sefer_parts(sefer) {
            if perek_id >= part.0 && perek_id <= part.1 {
                return Ok((si, part));
            }
        }
    }
    bail!("No corpus perek for perekId {perek_id}")
}

/// The marker segment type at a unit's closing coordinate, from the
/// corpus (independent of the unit's `closing_break` field).
fn marker_at(sefarim: &[Sefer], end: &Coordinate) -> Result<Option<String>> {
    let (_sefer_idx, (perek_from, _perek_to, perakim)) = locate_perek(sefarim, end.perek_id)?;
    let perek = perakim
        .get((end.perek_id - perek_from) as usize)
        .context("perek id outside its part")?;
    let pasuk = perek
        .pesukim
        .get(end.pasuk as usize - 1)
        .context("end pasuk outside its perek")?;
    let Some(si) = end.segment_index else {
        return Ok(None);
    };
    Ok(pasuk
        .segments
        .get(si as usize)
        .map(|seg| seg.segment_type.clone()))
}

/// Load and parse the sedarim reference fixture.
pub fn load_reference(path: &Path) -> Result<SedarimReference> {
    let text = std::fs::read_to_string(path)
        .with_context(|| format!("Failed to read sedarim reference {}", path.display()))?;
    serde_json::from_str(&text)
        .with_context(|| format!("Failed to parse sedarim reference {}", path.display()))
}

/// Run the full verification: reference integrity, corpus unit
/// integrity, and per-entry alignment classification.
pub fn verify(
    sefarim: &[Sefer],
    reference: &SedarimReference,
    corpus_label: &str,
) -> Result<SedarimVerification> {
    let units = derive_masora_units(sefarim).context("derive masora units")?;
    let mut checks: Vec<VerificationCheck> = Vec::new();
    let mut verified: Vec<VerifiedSeder> = Vec::new();

    // ptuha/stuma marker count per sefer — a zero means the sefer's
    // division degenerates to a single unit and interior
    // classifications there carry no real evidence.
    let marker_counts: Vec<usize> = sefarim
        .iter()
        .map(|sefer| {
            sefer_parts(sefer)
                .iter()
                .flat_map(|(_, _, perakim)| perakim.iter())
                .flat_map(|perek| perek.pesukim.iter())
                .flat_map(|pasuk| pasuk.segments.iter())
                .filter(|s| s.segment_type == "ptuha" || s.segment_type == "stuma")
                .count()
        })
        .collect();

    // --- Reference integrity -------------------------------------------------

    check(
        &mut checks,
        "reference-group-count",
        reference.groups.len() == 19,
        format!("{} book groups", reference.groups.len()),
    );

    let total: usize = reference.groups.iter().map(|g| g.sedarim.len()).sum();
    let regular: usize = reference
        .groups
        .iter()
        .flat_map(|g| g.sedarim.iter())
        .filter(|e| !e.paren)
        .count();
    let parenthesized = total - regular;
    check(
        &mut checks,
        "reference-entry-counts",
        total == 297 && regular == 293 && parenthesized == 4,
        format!("{total} entries: {regular} numbered + {parenthesized} parenthesized"),
    );

    // Seder numbering: regular entries spell consecutive Hebrew
    // numerals; parenthesized entries sit outside the sequence.
    let mut numbering_problems = Vec::new();
    for group in &reference.groups {
        let mut expected = 1i32;
        for entry in &group.sedarim {
            let Ok(value) = from_letters(&entry.seder) else {
                numbering_problems.push(format!(
                    "{} סדר {}: not a Hebrew numeral",
                    group.book, entry.seder
                ));
                continue;
            };
            if entry.paren {
                // A parenthesized number belongs to the manuscript
                // tradition that contains it, so it only needs to be a
                // plausible position in that tradition's count.
                if value < 1 || value > expected {
                    numbering_problems.push(format!(
                        "{} ({}): number {} outside its sequence",
                        group.book, entry.seder, value
                    ));
                }
                continue;
            }
            if value != expected || entry.seder != to_letters(expected) {
                numbering_problems.push(format!(
                    "{} סדר {}: expected {}",
                    group.book,
                    entry.seder,
                    to_letters(expected)
                ));
            }
            expected += 1;
        }
    }
    check(
        &mut checks,
        "seder-numbering",
        numbering_problems.is_empty(),
        if numbering_problems.is_empty() {
            "numbered entries run consecutively; parenthesized entries sit outside the sequence"
                .to_string()
        } else {
            numbering_problems.join("; ")
        },
    );

    // Letter/number agreement inside each entry.
    let mut coord_problems = Vec::new();
    for group in &reference.groups {
        for entry in &group.sedarim {
            if from_letters(&entry.perek).ok() != Some(entry.perek_n) {
                coord_problems.push(format!(
                    "{} {} perek {}",
                    group.book, entry.seder, entry.perek
                ));
            }
            if from_letters(&entry.pasuk).ok() != Some(entry.pasuk_n) {
                coord_problems.push(format!(
                    "{} {} pasuk {}",
                    group.book, entry.seder, entry.pasuk
                ));
            }
        }
    }
    check(
        &mut checks,
        "letter-number-agreement",
        coord_problems.is_empty(),
        if coord_problems.is_empty() {
            "every perek/pasuk letters string equals its numeric field".to_string()
        } else {
            coord_problems.join("; ")
        },
    );

    // --- Resolution + classification -----------------------------------------

    // Unit starts keyed by (perek_id, pasuk) — the boundaries a seder
    // head could coincide with.
    let mut start_index: HashMap<(i32, i32), Starts> = HashMap::new();
    for unit in &units {
        let start = &unit.ranges[0].start;
        let starts = start_index
            .entry((start.perek_id, start.pasuk))
            .or_default();
        match start.segment_index {
            None => starts.whole_pasuk = true,
            Some(si) => starts.mid_pasuk = Some(si),
        }
    }

    let mut resolution_problems = Vec::new();
    let mut order_problems = Vec::new();
    let mut group_start_problems = Vec::new();

    for group in &reference.groups {
        let mut last_position: Option<(i32, i32)> = None;
        let mut first_regular_seen = false;
        for entry in &group.sedarim {
            let sub = entry.sub_book.as_deref();
            let resolved = resolve_part(sefarim, &group.book, sub).and_then(|part| {
                let display = part.display.to_string();
                resolve_head(&part, entry, &group.book).map(|head| (display, head))
            });
            match resolved {
                Ok((display, head)) => {
                    let reference_text = format!("{display} {} {}", entry.perek, entry.pasuk);
                    let position = (head.perek_id, head.pasuk);

                    // Ordered, gap-free seder coverage inside the group.
                    if last_position.is_some_and(|last| position <= last) {
                        order_problems.push(format!(
                            "{reference_text} does not follow the previous entry"
                        ));
                    }
                    last_position = Some(position);

                    // First numbered seder must open at the book's
                    // first pasuk so coverage starts at the start.
                    if !entry.paren && !first_regular_seen {
                        first_regular_seen = true;
                        if head.pasuk != 1 || head.perek_id != head.part_perek_from {
                            group_start_problems.push(format!(
                                "{} first seder is {reference_text}, not the book's first pasuk",
                                group.book
                            ));
                        }
                    }

                    let (alignment, unit) = classify(&units, &start_index, &head);
                    let disposition = disposition(group, entry, &alignment);
                    verified.push(VerifiedSeder {
                        book: group.book.clone(),
                        seder: entry.seder.clone(),
                        paren: entry.paren,
                        reference: reference_text,
                        perek_id: head.perek_id,
                        pasuk: head.pasuk,
                        alignment,
                        disposition,
                        unit_id: unit.unit_id,
                        unit_heading: unit.heading.clone(),
                        unit_closing_break: unit.closing_break.map(str::to_string),
                        marker_free_sefer: marker_counts[head.sefer_idx] == 0,
                    });
                }
                Err(err) => {
                    resolution_problems.push(format!("{} {}: {err}", group.book, entry.seder));
                    verified.push(VerifiedSeder {
                        book: group.book.clone(),
                        seder: entry.seder.clone(),
                        paren: entry.paren,
                        reference: format!(
                            "{} {} {}",
                            sub.unwrap_or(&group.book),
                            entry.perek,
                            entry.pasuk
                        ),
                        perek_id: 0,
                        pasuk: 0,
                        alignment: SederAlignment::Unresolved {
                            reason: err.to_string(),
                        },
                        disposition: Disposition::NeedsAdjudication,
                        unit_id: 0,
                        unit_heading: String::new(),
                        unit_closing_break: None,
                        marker_free_sefer: false,
                    });
                }
            }
        }
    }

    check(
        &mut checks,
        "references-resolve",
        resolution_problems.is_empty(),
        if resolution_problems.is_empty() {
            "every entry resolves inside the corpus".to_string()
        } else {
            resolution_problems.join("; ")
        },
    );

    check(
        &mut checks,
        "ordered-no-repeats",
        order_problems.is_empty(),
        if order_problems.is_empty() {
            "seder heads increase strictly inside every group — no omissions or repeats".to_string()
        } else {
            order_problems.join("; ")
        },
    );

    check(
        &mut checks,
        "first-seder-at-book-start",
        group_start_problems.is_empty(),
        if group_start_problems.is_empty() {
            "every group's first numbered seder opens at the book's first pasuk".to_string()
        } else {
            group_start_problems.join("; ")
        },
    );

    // תרי עשר sub-book mapping: every named member must exist, and
    // members the list never names must sit inside a seder's span
    // (between two consecutive heads or after the last head).
    let trei = reference.groups.iter().find(|g| g.book == "תרי עשר");
    let mut sub_problems = Vec::new();
    if let Some(group) = trei {
        let mut missing = Vec::new();
        for member in TREI_ASAR_MEMBERS {
            if !sefarim.iter().any(|s| s.name == *member) {
                missing.push(*member);
            }
        }
        if !missing.is_empty() {
            sub_problems.push(format!("missing corpus sefarim: {}", missing.join(", ")));
        }
        let positions: Vec<i32> = verified
            .iter()
            .filter(|v| v.book == "תרי עשר")
            .map(|v| v.perek_id)
            .collect();
        let last_head = positions.iter().max().copied().unwrap_or(0);
        for member in TREI_ASAR_MEMBERS {
            if group
                .sedarim
                .iter()
                .any(|e| e.sub_book.as_deref() == Some(member))
            {
                continue;
            }
            let sefer = sefarim.iter().find(|s| s.name == *member);
            match sefer {
                Some(sefer) if sefer.perek_to < last_head => {
                    // Covered inside an earlier seder's span.
                }
                Some(sefer) if sefer.perek_from > positions.iter().min().copied().unwrap_or(0) => {
                    let covered = positions
                        .windows(2)
                        .any(|w| sefer.perek_from > w[0] && sefer.perek_from < w[1])
                        || sefer.perek_from > last_head;
                    if !covered {
                        sub_problems.push(format!("{member} is not covered by any seder span"));
                    }
                }
                _ => {}
            }
        }
    }
    check(
        &mut checks,
        "sub-book-mapping",
        sub_problems.is_empty(),
        if sub_problems.is_empty() {
            "sub-book labels map to corpus additionals; unreferenced תרי עשר members lie inside seder spans"
                .to_string()
        } else {
            sub_problems.join("; ")
        },
    );

    // --- Corpus division integrity -------------------------------------------

    let ptuha = units
        .iter()
        .filter(|u| u.closing_break == Some("ptuha"))
        .count();
    let stuma = units
        .iter()
        .filter(|u| u.closing_break == Some("stuma"))
        .count();
    let sefer_ends = units.iter().filter(|u| u.closing_break.is_none()).count();
    check(
        &mut checks,
        "unit-counts",
        units.len() == 3197 && ptuha == 1181 && stuma == 1981 && sefer_ends == 35,
        format!(
            "{} units ({ptuha} ptuha, {stuma} stuma, {sefer_ends} sefer-end)",
            units.len()
        ),
    );

    // A sefer with no ptuha/stuma markers degenerates to one unit;
    // flag it so interior classifications there are not read as real
    // evidence. Today only תהילים and single-perek עובדיה are
    // marker-free (a known corpus gap for תהילים — Koren prints
    // parasha breaks throughout Psalms).
    let marker_free: Vec<&str> = sefarim
        .iter()
        .enumerate()
        .filter(|(i, _)| marker_counts[*i] == 0)
        .map(|(_, s)| s.name.as_str())
        .collect();
    check(
        &mut checks,
        "marker-free-sefarim",
        marker_free == ["עובדיה", "תהילים"],
        format!(
            "sefarim with no parasha markers: {}",
            marker_free.join(", ")
        ),
    );

    // Every marker-closed unit ends on a marker segment of the same
    // type, and consecutive units tile the sefer contiguously.
    let mut tiling_problems = Vec::new();
    let marker_count: usize = marker_counts.iter().sum();
    for sefer_idx in 0..sefarim.len() {
        let sefer_units: Vec<&ReadingUnit> = units
            .iter()
            .filter(|u| u.sefer_id == sefer_idx as i32 + 1)
            .collect();
        for window in sefer_units.windows(2) {
            let (unit, next) = (window[0], window[1]);
            let end = &unit.ranges[0].end;
            match marker_at(sefarim, end) {
                Ok(Some(t)) if Some(t.as_str()) == unit.closing_break => {}
                other => tiling_problems.push(format!(
                    "unit {} ends on {:?}, expected a {:?} marker",
                    unit.unit_id, other, unit.closing_break
                )),
            }
            match coordinate_after_end(sefarim, end) {
                Ok(Some(expected)) if expected == next.ranges[0].start => {}
                other => tiling_problems.push(format!(
                    "unit {} does not follow unit {} contiguously (expected {:?})",
                    next.unit_id, unit.unit_id, other
                )),
            }
        }
        // Sefer-end unit: closed by the sefer's final pasuk.
        if sefer_units
            .last()
            .is_some_and(|last| last.closing_break.is_some())
        {
            tiling_problems.push(format!(
                "sefer {} last unit is not sefer-end",
                sefer_idx + 1
            ));
        }
    }
    check(
        &mut checks,
        "contiguous-tiling",
        tiling_problems.is_empty(),
        if tiling_problems.is_empty() {
            "units tile every sefer contiguously; each marker-closed end is a corpus marker"
                .to_string()
        } else {
            tiling_problems.join("; ")
        },
    );

    check(
        &mut checks,
        "marker-roundtrip",
        marker_count == ptuha + stuma,
        format!("{marker_count} corpus markers close {ptuha}+{stuma} units"),
    );

    let cross_perek = units
        .iter()
        .filter(|u| u.ranges[0].start.perek_id != u.ranges[0].end.perek_id)
        .count();
    check(
        &mut checks,
        "cross-perek-units",
        cross_perek == 153,
        format!("{cross_perek} units span perek boundaries"),
    );

    // --- Summary --------------------------------------------------------------

    let summary = AlignmentSummary {
        total,
        regular,
        parenthesized,
        parasha_boundary: verified
            .iter()
            .filter(|v| v.alignment == SederAlignment::ParashaBoundary)
            .count(),
        mid_pasuk_boundary: verified
            .iter()
            .filter(|v| matches!(v.alignment, SederAlignment::MidPasukBoundary { .. }))
            .count(),
        parasha_last_pasuk: verified
            .iter()
            .filter(|v| matches!(v.alignment, SederAlignment::ParashaLastPasuk { .. }))
            .count(),
        interior_of_parasha: verified
            .iter()
            .filter(|v| v.alignment == SederAlignment::InteriorOfParasha)
            .count(),
        unresolved: verified
            .iter()
            .filter(|v| matches!(v.alignment, SederAlignment::Unresolved { .. }))
            .count(),
        corpus_units: units.len(),
        ptuha_closing: ptuha,
        stuma_closing: stuma,
        sefer_end_closing: sefer_ends,
        cross_perek_units: cross_perek,
        mid_pasuk_unit_starts: units
            .iter()
            .filter(|u| u.ranges[0].start.segment_index.is_some())
            .count(),
    };

    Ok(SedarimVerification {
        reference_title: reference.provenance.title.clone(),
        reference_source_url: reference.provenance.source_url.clone(),
        reference_sha256: reference.provenance.sha256.clone(),
        corpus: corpus_label.to_string(),
        checks,
        summary,
        sedarim: verified,
    })
}

fn check(checks: &mut Vec<VerificationCheck>, name: &str, passed: bool, detail: String) {
    checks.push(VerificationCheck {
        name: name.to_string(),
        status: if passed { "pass" } else { "fail" }.to_string(),
        detail,
    });
}

/// Which boundary kinds a pasuk holds as unit starts. One pasuk can
/// hold both a whole-pasuk start and a later mid-pasuk start (a unit
/// that opens at the pasuk and is closed by a mid-verse marker).
#[derive(Default)]
struct Starts {
    whole_pasuk: bool,
    mid_pasuk: Option<i32>,
}

/// Classify one resolved head against the derived units. Returns the
/// alignment and the unit covering the head pasuk.
fn classify<'a>(
    units: &'a [ReadingUnit],
    start_index: &HashMap<(i32, i32), Starts>,
    head: &ResolvedHead,
) -> (SederAlignment, &'a ReadingUnit) {
    let unit = units
        .iter()
        .find(|u| unit_covers_pasuk(u, head.perek_id, head.pasuk))
        .expect("units tile the corpus, so every pasuk is covered");
    if let Some(starts) = start_index.get(&(head.perek_id, head.pasuk)) {
        // A whole-pasuk start means a boundary sits AT the seder head;
        // a mid-pasuk start alone means the corpus splits the head
        // verse itself.
        if starts.whole_pasuk {
            return (SederAlignment::ParashaBoundary, unit);
        }
        if let Some(segment_index) = starts.mid_pasuk {
            return (SederAlignment::MidPasukBoundary { segment_index }, unit);
        }
    }
    // The corpus marks a break after the seder's first verse itself:
    // the head pasuk closes a parasha.
    let last_segment = head
        .perek
        .pesukim
        .get(head.pasuk as usize - 1)
        .and_then(|p| p.segments.last())
        .map(|s| s.segment_type.as_str());
    if let Some(kind @ ("ptuha" | "stuma")) = last_segment {
        return (
            SederAlignment::ParashaLastPasuk {
                closing_break: kind.to_string(),
            },
            unit,
        );
    }
    (SederAlignment::InteriorOfParasha, unit)
}

/// Assign an adjudication status to an entry.
fn disposition(
    group: &SedarimGroup,
    entry: &SedarEntry,
    alignment: &SederAlignment,
) -> Disposition {
    if entry.paren {
        return Disposition::ManuscriptOnly;
    }
    match alignment {
        SederAlignment::ParashaBoundary | SederAlignment::MidPasukBoundary { .. } => {
            Disposition::Aligned
        }
        SederAlignment::Unresolved { .. } => Disposition::NeedsAdjudication,
        _ => {
            let documented = DOCUMENTED_MID_PARASHA
                .iter()
                .any(|(book, seder)| *book == group.book && *seder == entry.seder);
            if !documented {
                return Disposition::NeedsAdjudication;
            }
            // שמואל סדר ג is documented as the second pasuk of a
            // TWO-pasuk parasha, but the corpus parasha containing it
            // has three pesukim — a real shape difference between the
            // corpus parasha edition and the documented one.
            if group.book == "שמואל" && entry.seder == "ג" {
                return Disposition::EditionDivergence {
                    detail: "documented as the second pasuk of a two-pasuk parasha; the corpus parasha שמואל א ג יט-כא has three pesukim".to_string(),
                };
            }
            Disposition::DocumentedSystemDifference
        }
    }
}
