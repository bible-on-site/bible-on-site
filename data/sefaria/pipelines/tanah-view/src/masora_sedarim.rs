/// Hebrew numeral value of a letters string — inverse of
/// [`to_letters`]. A plain gematria sum covers every form in the
/// fixture, including טו/טז which sum correctly without
/// special-casing.
pub fn from_letters(letters: &str) -> Result<i32> {
    let mut sum = 0i32;
    for ch in letters.chars() {
        sum += match ch {
            'א' => 1,
            'ב' => 2,
            'ג' => 3,
            'ד' => 4,
            'ה' => 5,
            'ו' => 6,
            'ז' => 7,
            'ח' => 8,
            'ט' => 9,
            'י' => 10,
            'כ' | 'ך' => 20,
            'ל' => 30,
            'מ' | 'ם' => 40,
            'נ' | 'ן' => 50,
            'ס' => 60,
            'ע' => 70,
            'פ' | 'ף' => 80,
            'צ' | 'ץ' => 90,
            'ק' => 100,
            'ר' => 200,
            'ש' => 300,
            'ת' => 400,
            _ => bail!("Not a Hebrew numeral character: {ch:?} in {letters:?}"),
        };
    }
    if sum == 0 {
        bail!("Empty Hebrew numeral");
    }
    Ok(sum)
}

