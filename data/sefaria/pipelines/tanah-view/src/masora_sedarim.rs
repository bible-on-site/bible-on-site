//! Verification of the Tanach Yomi סדרים reference list against the
//! מסורה reading units derived from `ptuha`/`stuma` markers.
//!
//! The reference PDF (`חלוקת ה"סדרים" של המסורה`, tanachyomi.co.il)
//! lists the FIRST pasuk of every Masoretic seder in Neviim and
//! Ketuvim, numbered per תנ"ך קורן. Sedarim and ptuha/stuma parashot
//! are distinct Masoretic systems: masoretic literature documents
//! seder heads that open a parasha, heads that land on a parasha's
//! last pasuk, and heads that sit inside a parasha. This module
//! therefore does NOT expect every seder head to coincide with a
//! unit start — it classifies each listed head against the corpus so
//! divergences surface for adjudication instead of drifting silently.
//!
//! The extracted reference lives in `fixtures/masora-sedarim-
//! tanachyomi.json` with provenance (source URL, sha256, retrieval
//! date, extraction notes). The PDF covers Neviim and Ketuvim only;
//! Torah coverage is a documented source limitation, not evidence
//! that the Torah lacks a seder division.
//!
//! See docs/data/masora-sedarim-verification.md for the rendered
//! report (regenerated by `cargo make verify-masora-sedarim`).

