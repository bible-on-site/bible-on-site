//! Generate the sedarim verification report (markdown) and the
//! expected verification snapshot consumed by the parity test.
//!
//! `cargo make verify-masora-sedarim` regenerates both artifacts:
//!   - docs/data/masora-sedarim-verification.md
//!   - fixtures/masora-sedarim-verification.expected.json
//!
//! The expected snapshot is checked in so that corpus or fixture
//! changes cannot silently change the verification outcome — the
//! parity test fails until the snapshot is deliberately regenerated.

use anyhow::Result;
use std::fs;
use std::path::Path;

use crate::masora_sedarim::{self, Disposition, SedarimVerification};
use crate::models::Sefer;

/// Default report location, relative to the repository root.
const DEFAULT_REPORT: &str = "../../../../docs/data/masora-sedarim-verification.md";
/// Default expected-snapshot location, relative to the crate.
const DEFAULT_EXPECTED: &str = "fixtures/masora-sedarim-verification.expected.json";

pub fn generate(
    sefarim: &[Sefer],
    dump_name: &str,
    reference_path: &Path,
    report_out: Option<&Path>,
    expected_out: Option<&Path>,
) -> Result<()> {
    let reference = masora_sedarim::load_reference(reference_path)?;
    let verification = masora_sedarim::verify(sefarim, &reference, dump_name)?;

    let report_path = report_out
        .map(|p| p.to_path_buf())
        .unwrap_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).join(DEFAULT_REPORT));
    if let Some(parent) = report_path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(&report_path, render_markdown(&verification))?;
    println!("📄 Verification report: {}", report_path.display());

    let expected_path = expected_out
        .map(|p| p.to_path_buf())
        .unwrap_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).join(DEFAULT_EXPECTED));
    if let Some(parent) = expected_path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(&expected_path, serde_json::to_string_pretty(&verification)?)?;
    println!("📦 Expected snapshot: {}", expected_path.display());

    let failed: Vec<&str> = verification
        .checks
        .iter()
        .filter(|c| c.status == "fail")
        .map(|c| c.name.as_str())
        .collect();
    if failed.is_empty() {
        println!("✅ All verification checks passed");
    } else {
        println!("❌ Failed checks: {}", failed.join(", "));
    }
    let s = &verification.summary;
    println!(
        "   {} entries: {} parasha-boundary, {} mid-pasuk, {} parasha-last-pasuk, {} interior, {} unresolved",
        s.total,
        s.parasha_boundary,
        s.mid_pasuk_boundary,
        s.parasha_last_pasuk,
        s.interior_of_parasha,
        s.unresolved
    );
    Ok(())
}

fn disposition_label(disposition: &Disposition) -> &'static str {
    match disposition {
        Disposition::Aligned => "aligned",
        Disposition::DocumentedSystemDifference => "documented system difference",
        Disposition::ManuscriptOnly => "manuscript-only",
        Disposition::EditionDivergence { .. } => "edition divergence",
        Disposition::NeedsAdjudication => "needs adjudication",
    }
}

fn render_markdown(v: &SedarimVerification) -> String {
    let s = &v.summary;
    let mut out = String::new();
    out.push_str(
        "# מסורה sedarim verification — Tanach Yomi reference vs the shipped division\n\n",
    );
    out.push_str(
        "> Generated by `cargo make verify-masora-sedarim`. Do not edit by hand;\n\
         > regenerate from the pipeline so the report and the checked-in\n\
         > verification snapshot stay in sync.\n\n",
    );

    out.push_str("## What is compared\n\n");
    out.push_str(
        "The shipped מסורה division derives reading units from `ptuha`/`stuma`\n\
         parasha markers in the Sefaria corpus (see docs/data/reading-units.md).\n\
         The user-supplied reference — `חלוקת ה\"סדרים\" של המסורה`,\n\
         [prakim.pdf](https://www.tanachyomi.co.il/PDFFiles/prakim.pdf) — lists the\n\
         first pasuk of every Masoretic seder in Neviim and Ketuvim, numbered per\n\
         תנ\"ך קורן. **סדרים and פתוחה/סתומה are different Masoretic systems and\n\
         are not expected to coincide**: literature documents seder heads placed\n\
         at a parasha's start, at its last pasuk, and inside it (חלוקת התנ\"ך\n\
         לסדרים, Hebrew Wikipedia). This report therefore classifies every listed\n\
         seder head instead of expecting a 1:1 match.\n\n",
    );

    out.push_str("## Source\n\n");
    out.push_str(&format!(
        "- Reference: `{}` ({})\n",
        v.reference_title, v.reference_source_url
    ));
    out.push_str(&format!("- sha256: `{}`\n", v.reference_sha256));
    out.push_str("- Extraction: positional reconstruction of the PDF Hebrew text objects (RTL columns, split glyphs, merged header fragments), cross-checked entry-by-entry; the curated list is checked in at `data/sefaria/pipelines/tanah-view/fixtures/masora-sedarim-tanachyomi.json`.\n");
    out.push_str("- **The PDF covers Neviim and Ketuvim only — it lists no Torah sedarim.** That is a source limitation, not evidence that the Torah lacks a seder division (Koren's Torah sedarim are documented separately).\n");
    out.push_str("- Parenthesized seder numbers mark boundaries attested only in some ancient manuscripts; they are excluded from the numbered sequence.\n\n");

    out.push_str("## Alignment summary\n\n");
    out.push_str("| class | count | meaning |\n|---|---:|---|\n");
    out.push_str(&format!(
        "| parasha-boundary | {} | head pasuk opens a corpus parasha unit |\n",
        s.parasha_boundary
    ));
    out.push_str(&format!(
        "| mid-pasuk-boundary | {} | the corpus splits the head pasuk itself at a segment boundary |\n",
        s.mid_pasuk_boundary
    ));
    out.push_str(&format!(
        "| parasha-last-pasuk | {} | head pasuk is the last pasuk of a corpus parasha (break follows the seder's first verse) |\n",
        s.parasha_last_pasuk
    ));
    out.push_str(&format!(
        "| interior-of-parasha | {} | head pasuk sits strictly inside a corpus parasha |\n",
        s.interior_of_parasha
    ));
    if s.unresolved > 0 {
        out.push_str(&format!(
            "| unresolved | {} | entry could not be resolved in the corpus |\n",
            s.unresolved
        ));
    }
    out.push_str(&format!(
        "| **total** | **{}** | {} numbered + {} parenthesized |\n\n",
        s.total, s.regular, s.parenthesized
    ));
    out.push_str(&format!(
        "Corpus division: {} units ({} ptuha, {} stuma, {} sefer-end), {} cross-perek, {} mid-pasuk unit starts.\n\n",
        s.corpus_units, s.ptuha_closing, s.stuma_closing, s.sefer_end_closing, s.cross_perek_units, s.mid_pasuk_unit_starts
    ));
    let marker_free_count = v.sedarim.iter().filter(|e| e.marker_free_sefer).count();
    if marker_free_count > 0 {
        out.push_str(&format!(
            "**{marker_free_count} entries sit in marker-free sefarim** (תהילים, עובדיה — no ptuha/stuma\n\
             markers in the corpus, so the whole sefer is one unit). Their interior\n\
             classifications are degenerate: they carry no evidence about seder placement,\n\
             only about the corpus gap.\n\n",
        ));
    }

    out.push_str("## Verification checks\n\n");
    out.push_str("| check | status | detail |\n|---|---|---|\n");
    for c in &v.checks {
        out.push_str(&format!("| {} | {} | {} |\n", c.name, c.status, c.detail));
    }
    out.push('\n');

    // Per-book classification table.
    out.push_str("## Classification detail\n\n");
    out.push_str(
        "Disposition: **aligned** = the corpus already carries the boundary; **documented\n\
         system difference** = a mid-parasha seder head documented in masoretic\n\
         literature; **manuscript-only** = parenthesized boundary not in the numbered\n\
         tradition; **edition divergence** = the corpus parasha shape differs from the\n\
         documented edition; **needs adjudication** = consistent with the two-system\n\
         divergence, but lacking entry-specific evidence.\n\n",
    );
    let mut current_book = "";
    for e in &v.sedarim {
        if e.book != current_book {
            current_book = e.book.as_str();
            out.push_str(&format!("### {current_book}\n\n"));
            out.push_str("| סדר | מראה מקום | alignment | containing unit | disposition |\n");
            out.push_str("|---|---|---|---|---|\n");
        }
        let seder_label = if e.paren {
            format!("({})", e.seder)
        } else {
            e.seder.clone()
        };
        let mut alignment = match &e.alignment {
            masora_sedarim::SederAlignment::ParashaBoundary => "parasha-boundary".to_string(),
            masora_sedarim::SederAlignment::MidPasukBoundary { segment_index } => {
                format!("mid-pasuk-boundary (segment {segment_index})")
            }
            masora_sedarim::SederAlignment::ParashaLastPasuk { closing_break } => {
                format!("parasha-last-pasuk ({closing_break})")
            }
            masora_sedarim::SederAlignment::InteriorOfParasha => "interior-of-parasha".to_string(),
            masora_sedarim::SederAlignment::Unresolved { reason } => {
                format!("unresolved ({reason})")
            }
        };
        if e.marker_free_sefer {
            alignment.push_str(" — marker-free sefer");
        }
        let unit_evidence = if e.unit_id == 0 {
            "-".to_string()
        } else {
            format!("{} ({})", e.unit_heading, e.unit_id)
        };
        out.push_str(&format!(
            "| {seder_label} | {} | {alignment} | {unit_evidence} | {} |\n",
            e.reference,
            disposition_label(&e.disposition)
        ));
    }
    out.push('\n');

    // Adjudication section.
    let divergence: Vec<_> = v
        .sedarim
        .iter()
        .filter(|e| matches!(e.disposition, Disposition::EditionDivergence { .. }))
        .collect();
    let adjudication: Vec<_> = v
        .sedarim
        .iter()
        .filter(|e| e.disposition == Disposition::NeedsAdjudication)
        .collect();
    out.push_str("## Adjudication\n\n");
    out.push_str(&format!(
        "- {} seder heads align with a corpus boundary ({} parasha-boundary, {} mid-pasuk) — verified.\n",
        s.parasha_boundary + s.mid_pasuk_boundary,
        s.parasha_boundary,
        s.mid_pasuk_boundary
    ));
    out.push_str(
        "- Seder heads on parasha-final pesukim and inside parashot are the documented\n\
           majority pattern of the seder system, not evidence of a corpus defect. Any\n\
           product decision to adopt סדרים as a shipped division is a separate change\n\
           (issue #2108 tracks a פרשה division); this verification preserves the\n\
           ptuha/stuma derivation as-is.\n",
    );
    for e in &divergence {
        if let Disposition::EditionDivergence { detail } = &e.disposition {
            out.push_str(&format!(
                "- **{} סדר {} ({})**: {detail}.\n",
                e.book, e.seder, e.reference
            ));
        }
    }
    out.push_str(&format!(
        "- {} entries are marked needs-adjudication: mid-parasha/parasha-final heads\n\
           without entry-specific literature evidence. Where Sefaria's parasha edition\n\
           and Koren's printed edition disagree (documented for שמואל א ג), adjudication\n\
           needs a second parasha source such as כתר ארם צובא imagery.\n",
        adjudication.len()
    ));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn disposition_labels_cover_all_variants() {
        for d in [
            Disposition::Aligned,
            Disposition::DocumentedSystemDifference,
            Disposition::ManuscriptOnly,
            Disposition::EditionDivergence {
                detail: "x".to_string(),
            },
            Disposition::NeedsAdjudication,
        ] {
            assert!(!disposition_label(&d).is_empty());
        }
    }
}
