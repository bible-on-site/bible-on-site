//! Generate MySQL SQL file from pipeline output.
//!
//! Native asset IDs remain unchanged. MySQL imports stage those IDs, preserve
//! published identities by exact name, and replace only incoming work/chapter
//! pairs inside one transaction.

use anyhow::Result;
use std::fs;
use std::path::Path;

use crate::data::extract::{Extracted, Note, Parshan, Perush};

pub fn generate(
    extracted: &Extracted,
    dump_name: &str,
    output_to_dependant_modules: bool,
) -> Result<()> {
    let output_path = if output_to_dependant_modules {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../../mysql")
            .join("perushim_data.sql")
    } else {
        let outputs_dir = Path::new(env!("CARGO_MANIFEST_DIR")).join(".output");
        fs::create_dir_all(&outputs_dir)?;
        outputs_dir.join(format!("{}.perushim_data.sql", dump_name))
    };

    generate_sql(&output_path, extracted, dump_name)?;
    println!("📁 Written to: {}", output_path.display());

    Ok(())
}

pub fn generate_sql(path: &Path, extracted: &Extracted, dump_name: &str) -> Result<()> {
    let mut sql = String::new();

    sql.push_str("-- Generated by: cd data && cargo make generate-perushim-view-mysql\n");
    sql.push_str(&format!("-- Source: {}\n", dump_name));
    sql.push_str(&format!(
        "-- Generated at: {}\n",
        chrono::Utc::now().format("%Y-%m-%d %H:%M:%S UTC")
    ));
    sql.push_str(
        "-- Database selection handled by the executing tool (db-populator, Lambda, etc.)\n\n",
    );

    sql.push_str("SET NAMES utf8mb4;\n");
    // The Lambda importer prepends FOREIGN_KEY_CHECKS=0. Restore enforcement
    // explicitly instead of depending on the executing connection's default.
    sql.push_str("SET FOREIGN_KEY_CHECKS = 1;\n\n");
    sql.push_str(STAGING_SQL);

    generate_parshanim_sql(&mut sql, &extracted.parshanim);
    generate_perushim_sql(&mut sql, &extracted.perushim);
    generate_notes_sql(&mut sql, &extracted.notes);

    sql.push_str(MERGE_SQL);

    fs::write(path, sql)?;

    Ok(())
}

// Temporary InnoDB tables and their indexes are created before BEGIN. Their
// native IDs never reach published tables without an explicit mapping. The
// generated binary key also rejects duplicate incoming names, including under
// case-insensitive or space-padding database collations.
const STAGING_SQL: &str = r#"-- Session-local staging. No published data is changed here.
DROP TEMPORARY TABLE IF EXISTS _perushim_import_parshan;
DROP TEMPORARY TABLE IF EXISTS _perushim_import_perush;
DROP TEMPORARY TABLE IF EXISTS _perushim_import_note;
DROP TEMPORARY TABLE IF EXISTS _perushim_import_parshan_map;
DROP TEMPORARY TABLE IF EXISTS _perushim_import_perush_map;
DROP TEMPORARY TABLE IF EXISTS _perushim_import_pairs;
DROP TEMPORARY TABLE IF EXISTS _perushim_import_changed_pairs;
DROP TEMPORARY TABLE IF EXISTS _perushim_import_guard;
CREATE TEMPORARY TABLE _perushim_import_parshan (
    id BIGINT NOT NULL PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    name_bytes VARBINARY(800) GENERATED ALWAYS AS (CAST(name AS BINARY)) STORED,
    birth_year SMALLINT DEFAULT NULL,
    has_pic TINYINT NOT NULL,
    UNIQUE KEY (name_bytes)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TEMPORARY TABLE _perushim_import_perush (
    id BIGINT NOT NULL PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    name_bytes VARBINARY(800) GENERATED ALWAYS AS (CAST(name AS BINARY)) STORED,
    parshan_id BIGINT NOT NULL,
    comp_date VARCHAR(100) DEFAULT NULL,
    pub_date VARCHAR(100) DEFAULT NULL,
    priority SMALLINT NOT NULL,
    UNIQUE KEY (name_bytes)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TEMPORARY TABLE _perushim_import_note (
    perush_id BIGINT NOT NULL,
    perek_id SMALLINT NOT NULL,
    pasuk SMALLINT NOT NULL,
    note_idx SMALLINT NOT NULL,
    note_content MEDIUMTEXT NOT NULL,
    PRIMARY KEY (perush_id, perek_id, pasuk, note_idx)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TEMPORARY TABLE _perushim_import_parshan_map (
    native_id BIGINT NOT NULL PRIMARY KEY,
    live_id BIGINT NOT NULL UNIQUE
) ENGINE=InnoDB;
CREATE TEMPORARY TABLE _perushim_import_perush_map (
    native_id BIGINT NOT NULL PRIMARY KEY,
    live_id BIGINT NOT NULL UNIQUE
) ENGINE=InnoDB;
CREATE TEMPORARY TABLE _perushim_import_pairs (
    perush_id BIGINT NOT NULL,
    perek_id SMALLINT NOT NULL,
    PRIMARY KEY (perush_id, perek_id)
) ENGINE=InnoDB;
CREATE TEMPORARY TABLE _perushim_import_changed_pairs (
    perush_id BIGINT NOT NULL,
    perek_id SMALLINT NOT NULL,
    PRIMARY KEY (perush_id, perek_id)
) ENGINE=InnoDB;
CREATE TEMPORARY TABLE _perushim_import_guard (
    id TINYINT NOT NULL PRIMARY KEY
) ENGINE=InnoDB;
INSERT INTO _perushim_import_guard (id) VALUES (1);

"#;

const MERGE_SQL: &str = r#"-- Only this transaction changes published identities, metadata or notes.
SET TRANSACTION ISOLATION LEVEL REPEATABLE READ;
BEGIN;
SELECT id FROM parshan ORDER BY id FOR UPDATE;
SELECT id FROM perush ORDER BY id FOR UPDATE;
-- These locking reads must precede every snapshot read in this transaction.
-- A duplicate guard key fails regardless of CHECK support or strict SQL mode.
INSERT INTO _perushim_import_guard (id)
SELECT 1 FROM information_schema.TABLES
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME IN ('parshan', 'perush', 'note', 'tanah_note_metric', 'tanah_perush_metric')
  AND COALESCE(ENGINE, '') <> 'InnoDB' LIMIT 1;
INSERT INTO _perushim_import_guard (id)
SELECT 1 FROM _perushim_import_perush AS incoming
LEFT JOIN _perushim_import_parshan AS author ON author.id = incoming.parshan_id
WHERE author.id IS NULL LIMIT 1;
INSERT INTO _perushim_import_guard (id)
SELECT 1 FROM _perushim_import_note AS incoming
LEFT JOIN _perushim_import_perush AS work ON work.id = incoming.perush_id
WHERE work.id IS NULL LIMIT 1;
SET @perushim_author_id_floor = (SELECT GREATEST(0, COALESCE(MAX(id), 0)) FROM parshan);
SET @perushim_work_id_floor = (SELECT GREATEST(0, COALESCE(MAX(id), 0)) FROM perush);
-- Duplicate exact live names fail the native PK. Duplicate mapped identities
-- fail UNIQUE(live_id). No ambiguous match can silently select an identity.
INSERT INTO _perushim_import_parshan_map (native_id, live_id)
SELECT incoming.id, published.id FROM _perushim_import_parshan AS incoming
JOIN parshan AS published ON BINARY published.name = BINARY incoming.name;
INSERT INTO _perushim_import_parshan_map (native_id, live_id)
SELECT incoming.id, @perushim_author_id_floor + ROW_NUMBER() OVER (ORDER BY incoming.id)
FROM _perushim_import_parshan AS incoming
LEFT JOIN parshan AS published ON BINARY published.name = BINARY incoming.name
WHERE published.id IS NULL;
INSERT INTO _perushim_import_perush_map (native_id, live_id)
SELECT incoming.id, published.id FROM _perushim_import_perush AS incoming
JOIN perush AS published ON BINARY published.name = BINARY incoming.name;
INSERT INTO _perushim_import_perush_map (native_id, live_id)
SELECT incoming.id, @perushim_work_id_floor + ROW_NUMBER() OVER (ORDER BY incoming.id)
FROM _perushim_import_perush AS incoming
LEFT JOIN perush AS published ON BINARY published.name = BINARY incoming.name
WHERE published.id IS NULL;
INSERT INTO _perushim_import_guard (id)
SELECT 1 FROM _perushim_import_parshan AS incoming
LEFT JOIN _perushim_import_parshan_map AS mapped ON mapped.native_id = incoming.id
WHERE mapped.live_id IS NULL LIMIT 1;
INSERT INTO _perushim_import_guard (id)
SELECT 1 FROM _perushim_import_perush AS incoming
LEFT JOIN _perushim_import_perush_map AS mapped ON mapped.native_id = incoming.id
WHERE mapped.live_id IS NULL LIMIT 1;
INSERT INTO _perushim_import_guard (id)
SELECT 1 FROM _perushim_import_note AS incoming
LEFT JOIN _perushim_import_perush_map AS mapped ON mapped.native_id = incoming.perush_id
WHERE mapped.live_id IS NULL LIMIT 1;
INSERT INTO _perushim_import_pairs (perush_id, perek_id)
SELECT DISTINCT mapped.live_id, incoming.perek_id
FROM _perushim_import_note AS incoming
JOIN _perushim_import_perush_map AS mapped ON mapped.native_id = incoming.perush_id;
-- Compare added or byte-different notes, then removed notes in incoming pairs.
-- IGNORE is used only to deduplicate this set, never to ignore imported data.
INSERT IGNORE INTO _perushim_import_changed_pairs (perush_id, perek_id)
SELECT DISTINCT mapped.live_id, incoming.perek_id
FROM _perushim_import_note AS incoming
JOIN _perushim_import_perush_map AS mapped ON mapped.native_id = incoming.perush_id
LEFT JOIN note AS published
  ON published.perush_id = mapped.live_id AND published.perek_id = incoming.perek_id
  AND published.pasuk = incoming.pasuk AND published.note_idx = incoming.note_idx
WHERE published.perush_id IS NULL OR BINARY published.note_content <> BINARY incoming.note_content;
INSERT IGNORE INTO _perushim_import_changed_pairs (perush_id, perek_id)
SELECT DISTINCT published.perush_id, published.perek_id
FROM note AS published
JOIN _perushim_import_pairs AS pair
  ON pair.perush_id = published.perush_id AND pair.perek_id = published.perek_id
JOIN _perushim_import_perush_map AS mapped ON mapped.live_id = published.perush_id
LEFT JOIN _perushim_import_note AS incoming
  ON incoming.perush_id = mapped.native_id AND incoming.perek_id = published.perek_id
  AND incoming.pasuk = published.pasuk AND incoming.note_idx = published.note_idx
WHERE incoming.perush_id IS NULL;
-- Keep published names, IDs and existing non-null metadata. A curated picture
-- flag must not disappear because a source catalog has no picture metadata.
INSERT INTO parshan (id, name, birth_year, has_pic)
SELECT mapped.live_id, incoming.name, incoming.birth_year, incoming.has_pic
FROM _perushim_import_parshan AS incoming
JOIN _perushim_import_parshan_map AS mapped ON mapped.native_id = incoming.id
LEFT JOIN parshan AS published ON published.id = mapped.live_id
WHERE published.id IS NULL;
UPDATE parshan AS published
JOIN _perushim_import_parshan_map AS mapped ON mapped.live_id = published.id
JOIN _perushim_import_parshan AS incoming ON incoming.id = mapped.native_id
SET published.birth_year = COALESCE(published.birth_year, incoming.birth_year),
    published.has_pic = GREATEST(published.has_pic, incoming.has_pic);
INSERT INTO perush (id, name, parshan_id, comp_date, pub_date, priority)
SELECT mapped.live_id, incoming.name, author.live_id, incoming.comp_date,
       incoming.pub_date, incoming.priority
FROM _perushim_import_perush AS incoming
JOIN _perushim_import_perush_map AS mapped ON mapped.native_id = incoming.id
JOIN _perushim_import_parshan_map AS author ON author.native_id = incoming.parshan_id
LEFT JOIN perush AS published ON published.id = mapped.live_id
WHERE published.id IS NULL;
UPDATE perush AS published
JOIN _perushim_import_perush_map AS mapped ON mapped.live_id = published.id
JOIN _perushim_import_perush AS incoming ON incoming.id = mapped.native_id
JOIN _perushim_import_parshan_map AS author ON author.native_id = incoming.parshan_id
SET published.parshan_id = author.live_id,
    published.comp_date = COALESCE(published.comp_date, incoming.comp_date),
    published.pub_date = COALESCE(published.pub_date, incoming.pub_date),
    published.priority = incoming.priority;
-- Optional metric tables may not exist on a fresh bootstrap. Changed notes
-- invalidate their derived metrics in the same transaction as the replacement.
SET @perushim_metric_delete = IF(
    EXISTS(SELECT 1 FROM information_schema.TABLES
           WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tanah_note_metric'),
    'DELETE metric FROM tanah_note_metric AS metric JOIN _perushim_import_changed_pairs AS changed ON changed.perush_id = metric.perush_id AND changed.perek_id = metric.perek_id',
    'SELECT 1');
PREPARE perushimMetricDelete FROM @perushim_metric_delete;
EXECUTE perushimMetricDelete;
DEALLOCATE PREPARE perushimMetricDelete;
SET @perushim_metric_delete = IF(
    EXISTS(SELECT 1 FROM information_schema.TABLES
           WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tanah_perush_metric'),
    'DELETE metric FROM tanah_perush_metric AS metric JOIN _perushim_import_changed_pairs AS changed ON changed.perush_id = metric.perush_id AND changed.perek_id = metric.perek_id',
    'SELECT 1');
PREPARE perushimMetricDelete FROM @perushim_metric_delete;
EXECUTE perushimMetricDelete;
DEALLOCATE PREPARE perushimMetricDelete;
DELETE published FROM note AS published
JOIN _perushim_import_changed_pairs AS incoming
  ON incoming.perush_id = published.perush_id AND incoming.perek_id = published.perek_id;
INSERT INTO note (perush_id, perek_id, pasuk, note_idx, note_content)
SELECT mapped.live_id, incoming.perek_id, incoming.pasuk, incoming.note_idx, incoming.note_content
FROM _perushim_import_note AS incoming
JOIN _perushim_import_perush_map AS mapped ON mapped.native_id = incoming.perush_id
JOIN _perushim_import_changed_pairs AS changed
  ON changed.perush_id = mapped.live_id AND changed.perek_id = incoming.perek_id;
COMMIT;
DROP TEMPORARY TABLE _perushim_import_changed_pairs;
DROP TEMPORARY TABLE _perushim_import_pairs;
DROP TEMPORARY TABLE _perushim_import_perush_map;
DROP TEMPORARY TABLE _perushim_import_parshan_map;
DROP TEMPORARY TABLE _perushim_import_note;
DROP TEMPORARY TABLE _perushim_import_perush;
DROP TEMPORARY TABLE _perushim_import_parshan;
DROP TEMPORARY TABLE _perushim_import_guard;
"#;

fn escape_sql(s: &str) -> String {
    // Use SQL-standard doubled-quote escaping ('') instead of backslash (\')
    // to avoid issues with NO_BACKSLASH_ESCAPES mode and Lambda SQL parsers.
    s.replace('\\', "\\\\")
        .replace('\'', "''")
        .replace('\n', "\\n")
        .replace('\r', "\\r")
        .replace('\t', "\\t")
}

fn generate_parshanim_sql(sql: &mut String, parshanim: &[Parshan]) {
    sql.push_str("-- parshan\n");
    for p in parshanim {
        let birth = p
            .birth_year
            .map(|y| y.to_string())
            .unwrap_or_else(|| "NULL".to_string());
        sql.push_str(&format!(
            "INSERT INTO _perushim_import_parshan (id, name, birth_year, has_pic) VALUES ({}, '{}', {}, {});\n",
            p.id,
            escape_sql(&p.name),
            birth,
            if p.has_pic { 1 } else { 0 }
        ));
    }
    sql.push('\n');
}

fn generate_perushim_sql(sql: &mut String, perushim: &[Perush]) {
    sql.push_str("-- perush\n");
    for p in perushim {
        let comp_date_str = p
            .comp_date
            .as_ref()
            .map(|s| format!("'{}'", escape_sql(s)))
            .unwrap_or_else(|| "NULL".to_string());
        let pub_date_str = p
            .pub_date
            .as_ref()
            .map(|s| format!("'{}'", escape_sql(s)))
            .unwrap_or_else(|| "NULL".to_string());

        sql.push_str(&format!(
            "INSERT INTO _perushim_import_perush (id, name, parshan_id, comp_date, pub_date, priority) VALUES ({}, '{}', {}, {}, {}, {});\n",
            p.id,
            escape_sql(&p.name),
            p.parshan_id,
            comp_date_str,
            pub_date_str,
            p.priority
        ));
    }
    sql.push('\n');
}

/// Batch size for multi-row INSERT statements.
/// Keeps each statement well under MySQL's `max_allowed_packet` default (64 MB).
const NOTES_BATCH_SIZE: usize = 500;

fn generate_notes_sql(sql: &mut String, notes: &[Note]) {
    sql.push_str("-- note\n");
    for chunk in notes.chunks(NOTES_BATCH_SIZE) {
        sql.push_str(
            "INSERT INTO _perushim_import_note (perush_id, perek_id, pasuk, note_idx, note_content) VALUES\n",
        );
        for (i, n) in chunk.iter().enumerate() {
            if i > 0 {
                sql.push_str(",\n");
            }
            sql.push_str(&format!(
                "({}, {}, {}, {}, '{}')",
                n.perush_id,
                n.perek_id,
                n.pasuk,
                n.note_idx,
                escape_sql(&n.note_content)
            ));
        }
        sql.push_str(";\n");
    }
    sql.push('\n');
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::commands::fixtures::temp_dir;

    fn sample_extracted(note_count: usize) -> Extracted {
        Extracted {
            parshanim: vec![
                Parshan {
                    id: 1,
                    name: "Rashi's \\ path".to_string(),
                    birth_year: Some(1040),
                    has_pic: true,
                },
                Parshan {
                    id: 2,
                    name: "Unknown".to_string(),
                    birth_year: None,
                    has_pic: false,
                },
            ],
            perushim: vec![
                Perush {
                    id: 10,
                    name: "Commentary One".to_string(),
                    parshan_id: 1,
                    comp_date: Some("1100".to_string()),
                    pub_date: None,
                    priority: 20,
                },
                Perush {
                    id: 11,
                    name: "Commentary Two".to_string(),
                    parshan_id: 2,
                    comp_date: None,
                    pub_date: Some("1200".to_string()),
                    priority: 30,
                },
            ],
            notes: (0..note_count)
                .map(|idx| Note {
                    perush_id: 10,
                    perek_id: 1,
                    pasuk: (idx % 5) as i64 + 1,
                    note_idx: idx as i64,
                    note_content: format!("note '{idx}'\nline"),
                })
                .collect(),
        }
    }

    #[test]
    fn escape_sql_uses_standard_quotes_and_control_escapes() {
        assert_eq!(escape_sql("a\\b'c\nd\re\tf"), "a\\\\b''c\\nd\\re\\tf");
    }

    #[test]
    fn generate_parshanim_sql_handles_optional_birth_year_and_picture_flag() {
        let mut sql = String::new();

        generate_parshanim_sql(&mut sql, &sample_extracted(0).parshanim);

        assert!(sql.contains("-- parshan"));
        assert!(sql.contains("Rashi''s \\\\ path', 1040, 1"));
        assert!(sql.contains("'Unknown', NULL, 0"));
    }

    #[test]
    fn generate_perushim_sql_handles_optional_dates() {
        let mut sql = String::new();

        generate_perushim_sql(&mut sql, &sample_extracted(0).perushim);

        assert!(sql.contains("'Commentary One', 1, '1100', NULL, 20"));
        assert!(sql.contains("'Commentary Two', 2, NULL, '1200', 30"));
    }

    #[test]
    fn generate_notes_sql_batches_large_note_sets() {
        let mut sql = String::new();

        generate_notes_sql(&mut sql, &sample_extracted(NOTES_BATCH_SIZE + 1).notes);

        assert_eq!(sql.matches("INSERT INTO _perushim_import_note").count(), 2);
        assert!(sql.contains("(10, 1, 1, 0, 'note ''0''\\nline')"));
        assert!(sql.contains("(10, 1, 1, 500, 'note ''500''\\nline')"));
    }

    #[test]
    fn generate_sql_stages_native_ids_and_merges_without_destructive_replacement() {
        let dir = temp_dir("mysql");
        let path = dir.join("perushim.sql");

        generate_sql(&path, &sample_extracted(2), "dump-name").unwrap();

        let sql = fs::read_to_string(&path).unwrap();
        assert!(sql.contains("-- Source: dump-name"));
        assert!(sql.contains("SET NAMES utf8mb4;"));
        assert!(!sql.contains("SET FOREIGN_KEY_CHECKS = 0;"));
        assert!(!sql.contains("TRUNCATE"));
        assert!(!sql.contains("DROP TABLE"));
        assert!(sql.contains("INSERT INTO _perushim_import_perush (id, name, parshan_id"));
        assert!(sql.contains("VALUES (10, 'Commentary One', 1,"));
        assert!(sql.contains("INSERT INTO parshan"));
        assert!(sql.contains("INSERT INTO perush"));
        assert!(sql.contains("INSERT INTO note"));
        assert!(sql.contains("SET FOREIGN_KEY_CHECKS = 1;"));
        assert!(sql.contains("BINARY published.name = BINARY incoming.name"));
        assert!(sql.contains("UNIQUE KEY (name_bytes)"));
        assert!(sql.contains("live_id BIGINT NOT NULL UNIQUE"));

        let begin = sql.find("BEGIN;").unwrap();
        let commit = sql.find("COMMIT;").unwrap();
        let author_lock = sql
            .find("SELECT id FROM parshan ORDER BY id FOR UPDATE;")
            .unwrap();
        let work_lock = sql
            .find("SELECT id FROM perush ORDER BY id FOR UPDATE;")
            .unwrap();
        let allocation = sql.find("SET @perushim_author_id_floor").unwrap();
        assert!(sql.rfind("INSERT INTO _perushim_import_note").unwrap() < begin);
        assert!(begin < author_lock && author_lock < work_lock && work_lock < allocation);
        let transaction = &sql[begin..commit];
        assert!(!transaction.contains("CREATE "));
        assert!(!transaction.contains("DROP "));
        assert!(transaction.contains("DELETE published FROM note AS published"));
        assert!(transaction.contains("incoming.perek_id = published.perek_id"));
        assert!(transaction.contains("SELECT mapped.live_id, incoming.perek_id"));

        fs::remove_dir_all(&dir).ok();
    }
}
