/** Generate the canonical per-perek pasuk-count data migration from the corpus. */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const { values } = parseArgs({
	options: {
		output: { type: "string" },
		check: { type: "boolean", default: false },
	},
});
if (!values.output) {
	throw new Error("Required: --output");
}
const root = fileURLToPath(new URL("../../../", import.meta.url));
const corpusDir = resolve(root, "web/bible-on-site/src/data/db");
const corpusFiles = readdirSync(corpusDir).filter((name) =>
	/^sefaria-dump-.+\.tanah_view\.json$/.test(name),
);
if (corpusFiles.length !== 1) {
	throw new Error(
		`Expected exactly one sefaria-dump-*.tanah_view.json in ${corpusDir}, found ${corpusFiles.length}`,
	);
}
const corpus = JSON.parse(
	readFileSync(resolve(corpusDir, corpusFiles[0]), "utf8"),
);

const counts = new Map();
for (const book of corpus) {
	for (const volume of book.additionals ?? [book]) {
		for (const [perekIndex, perek] of volume.perakim.entries()) {
			const perekId = volume.perekFrom + perekIndex;
			if (counts.has(perekId)) {
				throw new Error(`Duplicate perek id ${perekId} in the corpus`);
			}
			const pasukCount = perek.pesukim.length;
			if (pasukCount < 1) {
				throw new Error(`Perek ${perekId} has no pesukim in the corpus`);
			}
			counts.set(perekId, pasukCount);
		}
	}
}
if (counts.size !== 929) {
	throw new Error(`Expected 929 canonical perakim, found ${counts.size}`);
}
for (let perekId = 1; perekId <= 929; perekId++) {
	if (!counts.has(perekId)) {
		throw new Error(`Missing canonical perek id ${perekId} in the corpus`);
	}
}

const sql = `-- Generated by data/mysql/scripts/generate-perek-pasuk-counts.mjs.
-- Source: ${corpusFiles[0]} (canonical corpus). Do not edit by hand —
-- regenerate the file when the corpus changes and verify it with --check.
-- pasuk_count is the number of pesukim the canonical corpus holds for the
-- perek. tanah_article_covering_source write paths validate pasuk
-- coordinates against it (#2189 / epic #2175 §3).
${[...counts.entries()]
	.sort(([a], [b]) => a - b)
	.map(
		([perekId, pasukCount]) =>
			`UPDATE tanah_perek SET pasuk_count = ${pasukCount} WHERE id = ${perekId};`,
	)
	.join("\n")}
`;
const outputPath = resolve(root, values.output);
if (values.check) {
	if (readFileSync(outputPath, "utf8").replace(/\r\n/g, "\n") !== sql) {
		throw new Error(
			"Pasuk-count migration differs from the canonical corpus; regenerate it",
		);
	}
} else {
	writeFileSync(outputPath, sql);
}
console.log(
	`${counts.size} perakim, ${[...counts.values()].reduce((a, b) => a + b, 0)} pesukim${values.check ? " (verified)" : ""}`,
);
