/** Generate a database content migration from exact canonical pasuk segments. */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const { values } = parseArgs({
	options: {
		entry: { type: "string" },
		"entity-type": { type: "string" },
		spellings: { type: "string" },
		prefixes: { type: "string", default: "ובכלמשה" },
		output: { type: "string" },
		check: { type: "boolean", default: false },
	},
});
if (
	!values.entry ||
	!values["entity-type"] ||
	!values.spellings ||
	!values.output
) {
	throw new Error("Required: --entry, --entity-type, --spellings, --output");
}
const root = fileURLToPath(new URL("../../../", import.meta.url));
const corpus = JSON.parse(
	readFileSync(
		resolve(
			root,
			"web/bible-on-site/src/data/db/sefaria-dump-5784-sivan-4.tanah_view.json",
		),
		"utf8",
	),
);
const spellings = values.spellings.split(",");
if (!spellings.every((spelling) => /^[א-ת]+$/u.test(spelling))) {
	throw new Error("Spellings must be comma-separated Hebrew words");
}
const prefixLetters = new Set(values.prefixes);
const matches = [];
for (const book of corpus) {
	for (const volume of book.additionals ?? [book]) {
		for (const [perekIndex, perek] of volume.perakim.entries()) {
			for (const [pasukIndex, pasuk] of perek.pesukim.entries()) {
				for (const [segmentIndex, segment] of pasuk.segments.entries()) {
					if (!("value" in segment)) continue;
					const word = segment.value.replace(/[^א-ת]/gu, "");
					if (
						!spellings.some(
							(spelling) =>
								word.endsWith(spelling) &&
								[...word.slice(0, -spelling.length)].every((letter) =>
									prefixLetters.has(letter),
								),
						)
					)
						continue;
					const perekId = volume.perekFrom + perekIndex;
					const pasukNumber = pasukIndex + 1;
					const digest = createHash("sha256")
						.update(
							`tanahpedia:${values.entry}:${values["entity-type"]}:${perekId}:${pasukNumber}:${segmentIndex}`,
						)
						.digest("hex")
						.slice(0, 32)
						.split("");
					// UUIDv8: a deterministic content identifier, not an authentication hash.
					digest[12] = "8";
					digest[16] = ((Number.parseInt(digest[16], 16) & 3) | 8).toString(16);
					const hash = digest.join("");
					const id = `${hash.slice(0, 8)}-${hash.slice(8, 12)}-${hash.slice(12, 16)}-${hash.slice(16, 20)}-${hash.slice(20)}`;
					matches.push({ id, perekId, pasukNumber, segmentIndex });
				}
			}
		}
	}
}
if (matches.length === 0) throw new Error("No occurrences found");
const quote = (value) => `'${value.replaceAll("'", "''")}'`;
const sql = `-- Generated by data/mysql/scripts/generate-tanahpedia-occurrences.mjs.
-- Entry: ${values.entry}. Spellings: ${spellings.join(", ")}. Hebrew prefixes: ${values.prefixes}.
-- ${matches.length} segment references. Insert missing references and preserve editorial records.
SET @occurrence_entity_id = (
    SELECT ee.entity_id
    FROM tanahpedia_entry_entity ee
    JOIN tanahpedia_entry ent ON ent.id = ee.entry_id
    JOIN tanahpedia_entity e ON e.id = ee.entity_id
    WHERE ent.unique_name = ${quote(values.entry)} AND e.entity_type = ${quote(values["entity-type"])}
    ORDER BY ee.id LIMIT 1
);

INSERT IGNORE INTO tanahpedia_entity_tanah_source (
    id, entity_id, perek_id, pasuk_number, segment_start, segment_end
)
SELECT matched.id, @occurrence_entity_id, matched.perek_id, matched.pasuk_number,
    matched.segment_index, matched.segment_index
FROM (
${matches
	.map(({ id, perekId, pasukNumber, segmentIndex }, index) =>
		index === 0
			? `    SELECT ${quote(id)} AS id, ${perekId} AS perek_id, ${pasukNumber} AS pasuk_number, ${segmentIndex} AS segment_index`
			: `    UNION ALL SELECT ${quote(id)}, ${perekId}, ${pasukNumber}, ${segmentIndex}`,
	)
	.join("\n")}
) matched
WHERE @occurrence_entity_id IS NOT NULL
    AND NOT EXISTS (
        SELECT 1 FROM tanahpedia_entity_tanah_source existing
        WHERE existing.entity_id = @occurrence_entity_id
            AND existing.perek_id = matched.perek_id
            AND existing.pasuk_number = matched.pasuk_number
            AND existing.segment_start = matched.segment_index
            AND existing.segment_end = matched.segment_index
    );
`;
const outputPath = resolve(root, values.output);
if (values.check) {
	if (readFileSync(outputPath, "utf8").replaceAll("\r\n", "\n") !== sql) {
		throw new Error(
			"Occurrence migration differs from the canonical corpus; regenerate it",
		);
	}
} else {
	writeFileSync(outputPath, sql);
}
const verseCount = new Set(
	matches.map((match) => `${match.perekId}:${match.pasukNumber}`),
).size;
console.log(
	`${values.entry}: ${matches.length} occurrences in ${verseCount} verses${values.check ? " (verified)" : ""}`,
);
