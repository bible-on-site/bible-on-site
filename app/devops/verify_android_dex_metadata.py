"""Assert an Android App Bundle carries the R8 metrics Play Console scores.

From February 2027, Play's technical quality requirements enforce a minimum 25%
optimization, obfuscation and shrinking on apps whose uncompressed DEX exceeds
10 MB. Play reads the embedded BUNDLE-METADATA entries — com.android.tools/r8.json
(generated by R8 via --build-metadata-output in Microsoft.Android.Sdk 36.1.118+)
and com.android.tools.build.obfuscation/proguard.map — from the uploaded bundle
itself, so this check gates the exact artifact that ships.

r8.json's `stats` object reports the share of DEX code R8 left alone as
`noObfuscationPercentage`, `noOptimizationPercentage` and
`noShrinkingPercentage` — Play's scores are the complements (100 − no*). The
verifier enforces all three ≥ 25% whenever the bundle's uncompressed DEX
crosses the applicability threshold, so a nominally-"enabled" but
sub-threshold build cannot pass the release gate.

https://support.google.com/googleplay/android-developer/answer/17492799
"""

import argparse
import json
from pathlib import Path
import re
import sys
import zipfile

R8_METADATA_ENTRY = "BUNDLE-METADATA/com.android.tools/r8.json"
PROGUARD_MAP_ENTRY = "BUNDLE-METADATA/com.android.tools.build.obfuscation/proguard.map"

# Play's applicability threshold for apps (games: 50 MB).
DEX_APPLICABILITY_BYTES = 10 * 1024 * 1024

# Play's enforced minimum for each of optimization/obfuscation/shrinking.
PLAY_MINIMUM_PERCENT = 25.0

# r8.json `stats` reports the share of untouched DEX code per stage; Play's
# score for each metric is 100 minus the corresponding no*Percentage value.
PLAY_SCORE_STATS = {
    "obfuscation": "noObfuscationPercentage",
    "optimization": "noOptimizationPercentage",
    "shrinking": "noShrinkingPercentage",
}

# ProGuard mapping lines: "original.name -> a.b.c:" for classes, indented
# "line:line:type original -> obfuscated" for members. An identity map entry
# (name mapped to itself) does not count — R8 emits those even when it
# obfuscates nothing, so counting them would rubber-stamp a -dontobfuscate build.
_CLASS_MAPPING = re.compile(rb"^(\S[^\n]*?) -> (\S+):\s*$", re.MULTILINE)
_MEMBER_MAPPING = re.compile(rb"^\s+\d+:\d+:.+? -> \S+\s*$", re.MULTILINE)

# R8 spells the optimization flag "isOptimizationsEnabled" (plural); older
# drafts and AGP metadata used "isOptimizationEnabled". Accept either.
_OPTIMIZATION_KEYS = ("isOptimizationsEnabled", "isOptimizationEnabled")


def _class_mappings(mapping: bytes) -> int:
    return sum(1 for original, obfuscated in _CLASS_MAPPING.findall(mapping)
               if original != obfuscated)


def _member_mappings(mapping: bytes) -> int:
    return len(_MEMBER_MAPPING.findall(mapping))


def dex_entries(archive: zipfile.ZipFile) -> list:
    return [
        (info, info.file_size)
        for info in archive.infolist()
        if re.fullmatch(r"[^/]+/dex/classes\d*\.dex", info.filename)
    ]


def load_r8_metadata(archive: zipfile.ZipFile) -> dict:
    if R8_METADATA_ENTRY not in archive.namelist():
        raise ValueError(
            f"AAB is missing {R8_METADATA_ENTRY} — the .NET for Android SDK must be "
            "36.1.118+ (workload set 10.0.402.1+) for R8 to emit build metadata that "
            "Play reads for code-optimization scoring."
        )
    raw = archive.read(R8_METADATA_ENTRY)
    try:
        document = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise ValueError(f"{R8_METADATA_ENTRY} is not valid JSON: {exc}") from exc
    options = document.get("options")
    if not isinstance(options, dict):
        raise ValueError(f"{R8_METADATA_ENTRY} has no 'options' object")
    return document


def required_flags(options: dict) -> dict:
    flags = {
        "isObfuscationEnabled": options.get("isObfuscationEnabled"),
        "isShrinkingEnabled": options.get("isShrinkingEnabled"),
    }
    flags["isOptimizationsEnabled"] = next(
        (options[key] for key in _OPTIMIZATION_KEYS if key in options), None
    )
    return flags


def play_scores(document: dict) -> dict:
    """Return Play's per-metric scores (100 − R8's reported untouched share)."""
    stats = document.get("stats")
    if not isinstance(stats, dict):
        raise ValueError(
            f"{R8_METADATA_ENTRY} has no 'stats' object — R8 reports the shares "
            "Play scores as noObfuscationPercentage/noOptimizationPercentage/"
            "noShrinkingPercentage there; without them the 25% requirements "
            "cannot be checked."
        )
    scores = {}
    for metric, key in PLAY_SCORE_STATS.items():
        untouched = stats.get(key)
        if not isinstance(untouched, (int, float)) or isinstance(untouched, bool):
            raise ValueError(
                f"{R8_METADATA_ENTRY} stats lacks a numeric '{key}' "
                f"(present: {sorted(stats)})"
            )
        scores[metric] = round(100.0 - untouched, 2)
    return scores


def verify(package: Path) -> dict:
    if not package.is_file():
        raise ValueError(f"AAB not found: {package}")
    with zipfile.ZipFile(package) as archive:
        document = load_r8_metadata(archive)
        flags = required_flags(document["options"])
        missing = [key for key, value in flags.items() if value is None]
        if missing:
            raise ValueError(
                f"{R8_METADATA_ENTRY} lacks expected option keys: {', '.join(missing)} "
                f"(present: {sorted(document['options'])})"
            )
        disabled = [key for key, value in flags.items() if value is not True]
        if disabled:
            raise ValueError(
                f"R8 build metadata reports disabled stages: {', '.join(disabled)} — "
                "an app with >10 MB uncompressed DEX needs 25% optimization, "
                "obfuscation and shrinking for Play uploads (February 2027)."
            )
        scores = play_scores(document)

        if PROGUARD_MAP_ENTRY not in archive.namelist():
            raise ValueError(
                f"AAB is missing {PROGUARD_MAP_ENTRY} — without the mapping Play "
                "cannot deobfuscate stack traces and the obfuscation metric is "
                "unverifiable."
            )
        mapping = archive.read(PROGUARD_MAP_ENTRY)
        classes = _class_mappings(mapping)
        members = _member_mappings(mapping)
        if classes == 0:
            raise ValueError(
                f"{PROGUARD_MAP_ENTRY} contains no renamed class mappings — a "
                "mapping that maps every name to itself means obfuscation did not "
                "actually run, whatever r8.json claims."
            )

        dex = dex_entries(archive)
    if not dex:
        raise ValueError("AAB contains no classes*.dex entries under <module>/dex/")
    dex_total = sum(size for _, size in dex)
    over_threshold = dex_total > DEX_APPLICABILITY_BYTES
    if over_threshold:
        below = {metric: score for metric, score in scores.items()
                 if score < PLAY_MINIMUM_PERCENT}
        if below:
            raise ValueError(
                "R8 stats fall short of Play's 25% minimum for a >10 MB DEX app: "
                + ", ".join(f"{metric} {score}%" for metric, score in below.items())
            )
    summary = {
        "package": package.name,
        "dexFiles": [info.filename for info, _ in dex],
        "dexUncompressedBytes": dex_total,
        "dexUncompressedMB": round(dex_total / (1024 * 1024), 2),
        "overApplicabilityThreshold": over_threshold,
        "r8Options": flags,
        "playScores": scores,
        "mappingClassRenames": classes,
        "mappingMemberRenames": members,
    }
    return summary


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--package", required=True, type=Path,
                        help="Path to the .aab produced by the Release build")
    args = parser.parse_args(argv)
    try:
        summary = verify(args.package)
    except (ValueError, zipfile.BadZipFile) as exc:
        print(f"::error::{exc}")
        return 1
    print(json.dumps(summary, indent=2))
    scope = "ABOVE" if summary["overApplicabilityThreshold"] else "below"
    scores = summary["playScores"]
    print(
        f"Uncompressed DEX {summary['dexUncompressedMB']} MB is {scope} Play's "
        "10 MB app threshold; r8.json reports obfuscation/shrinking/optimization "
        f"enabled with Play scores {scores['obfuscation']}%/{scores['shrinking']}%/"
        f"{scores['optimization']}% and proguard.map carries "
        f"{summary['mappingClassRenames']} class "
        f"and {summary['mappingMemberRenames']} member renames."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
