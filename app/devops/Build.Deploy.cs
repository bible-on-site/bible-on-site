    Target DeployGooglePlay => _ => _
        .Description("Deploy AAB to Google Play")
        .Requires(() => AabPath)
        .Requires(() => GooglePlayKeyFile)
        .Executes(() =>
        {
            var aabFile = (AbsolutePath)AabPath!;
            var keyFile = (AbsolutePath)GooglePlayKeyFile!;
            Assert.FileExists(aabFile, $"AAB file not found: {aabFile}");
            Assert.FileExists(keyFile, $"Service account key file not found: {keyFile}");

            var track = Production ? "production" : GooglePlayTrack;
            Serilog.Log.Information($"Uploading {aabFile.Name} to Google Play ({track} track)...");

            if (track == "production")
            {
                Serilog.Log.Warning("Deploying to PRODUCTION - will require Google review for new apps");
            }

            // #2970: Play rejects a malformed symbols archive only after the
            // bundle is already uploaded, stranding it in an uncommitted edit.
            // Validate the archive against this exact AAB before any store write.
            if (!string.IsNullOrEmpty(AndroidSymbolsPath))
            {
                var symbolsFile = (AbsolutePath)AndroidSymbolsPath!;
                Assert.FileExists(symbolsFile, $"Native symbols file not found: {symbolsFile}");
                LogSymbolCoverage(AndroidNativeSymbols.Validate(symbolsFile, aabFile));
                Serilog.Log.Information($"Validated native symbols archive {symbolsFile.Name} against {aabFile.Name}");
            }

            using var service = CreatePlayService(keyFile);

            // Create edit
            // Hebrew release notes are validated locally before any store
            // object exists — a bad file must not strand an open edit.
            var releaseNotes = ReadStoreReleaseNotes(ReleaseNotesFile, 500);

            var edit = service.Edits.Insert(new AppEdit(), GooglePlayPackageName).Execute();
            Serilog.Log.Information($"Created edit: {edit.Id}");

            long? uploadedVersionCode = null;
            var committed = false;
            try
            {
                // The localized language tag is proven from the store itself
                // inside the cleanup boundary: Play still resolves Hebrew
                // under the legacy "iw" listing code.
                var notesLanguage = releaseNotes is null
                    ? null
                    : HebrewListingLanguage(service, edit.Id);

                // Upload AAB
                using var aabStream = File.OpenRead(aabFile);
                var uploadRequest = service.Edits.Bundles.Upload(GooglePlayPackageName, edit.Id, aabStream, "application/octet-stream");
                var uploadProgress = UploadWithResume(uploadRequest);

                if (uploadProgress.Status != UploadStatus.Completed)
                {
                    Assert.Fail($"Upload failed: {uploadProgress.Exception?.Message}");
                }

                var bundle = uploadRequest.ResponseBody;
                var versionCode = bundle?.VersionCode
                    ?? throw new InvalidOperationException("Bundle upload returned no version code");
                uploadedVersionCode = versionCode;
                Serilog.Log.Information($"Uploaded bundle with version code: {versionCode}");

                // Upload native debug symbols for the version code just uploaded
                if (!string.IsNullOrEmpty(AndroidSymbolsPath))
                {
                    using var symbolsStream = File.OpenRead((AbsolutePath)AndroidSymbolsPath!);
                    var symbolsUpload = service.Edits.Deobfuscationfiles.Upload(
                        GooglePlayPackageName,
                        edit.Id,
                        (int)versionCode,
                        EditsResource.DeobfuscationfilesResource.UploadMediaUpload.DeobfuscationFileTypeEnum.NativeCode,
                        symbolsStream,
                        "application/octet-stream");
                    var symbolsProgress = symbolsUpload.Upload();
                    if (symbolsProgress.Status != UploadStatus.Completed)
                    {
                        Assert.Fail($"Native symbols upload failed for version code {versionCode} after the AAB was accepted; " +
                            $"no track assignment or commit was performed: {symbolsProgress.Exception?.Message}");
                    }
                    Serilog.Log.Information($"Uploaded native debug symbols for version code {versionCode}");
                }
                else
                {
                    Serilog.Log.Warning("No native debug symbols provided; Play Console will report them missing");
                }

                // Assign to track, carrying the localized Hebrew notes on this
                // release only — other localizations and tracks stay untouched.
                var trackUpdate = new Track
                {
                    Releases = new List<TrackRelease>
                    {
                        new()
                        {
                            Status = "completed",
                            VersionCodes = new List<long?> { versionCode },
                            ReleaseNotes = releaseNotes is null || notesLanguage is null
                                ? null
                                : new List<LocalizedText>
                                {
                                    new() { Language = notesLanguage, Text = releaseNotes }
                                }
                        }
                    }
                };
                var trackResponse = service.Edits.Tracks.Update(trackUpdate, GooglePlayPackageName, edit.Id, track).Execute();
                if (releaseNotes is not null)
                {
                    // The update response is supported evidence of what the
                    // store accepted — assert it before committing.
                    var accepted = trackResponse.Releases?
                        .FirstOrDefault(r => r.VersionCodes?.Contains(versionCode) == true)?
                        .ReleaseNotes?.FirstOrDefault(n => n.Language == notesLanguage)?.Text;
                    Assert.True(
                        accepted == releaseNotes,
                        "Google Play did not accept the exact Hebrew release notes on the track update");
                    Serilog.Log.Information($"Accepted {notesLanguage} release notes ({releaseNotes.Length} chars)");
                }
                Serilog.Log.Information($"Assigned to {track} track");

                // Commit edit
                var commitRequest = service.Edits.Commit(GooglePlayPackageName, edit.Id);
                commitRequest.Execute();
                committed = true;
                if (releaseNotes is not null)
                {
                    VerifyPlayReleaseNotes(service, track, versionCode, notesLanguage!, releaseNotes);
                }
                Serilog.Log.Information("Google Play upload complete");
            }
            finally
            {
                if (!committed)
                {
                    // Any failure after Edits.Insert leaves an uncommitted edit
                    // holding the uploaded bundle; discard it so the next
                    // deploy starts a clean edit instead of racing an
                    // abandoned one.
                    DiscardEdit(service, edit.Id, uploadedVersionCode);
                }
            }
        });

    /// <summary>
    /// Discards an uncommitted Play edit after a mid-deploy failure. The
    /// uploaded bundle lives only inside the edit, so deleting it leaves
    /// nothing published and lets the next run start a fresh edit. Best-effort:
    /// the original failure stays the actionable error, never the cleanup.
    /// </summary>
    static void DiscardEdit(AndroidPublisherService service, string editId, long? versionCode)
    {
        try
        {
            service.Edits.Delete(GooglePlayPackageName, editId).Execute();
            Serilog.Log.Warning(versionCode is null
                ? $"Discarded uncommitted Play edit {editId} after the deploy failed"
                : $"Discarded uncommitted Play edit {editId} holding uploaded bundle version code {versionCode}; no track release was published");
        }
        catch (Exception cleanup) when (cleanup is GoogleApiException or HttpRequestException
            or TaskCanceledException or IOException or AggregateException or InvalidOperationException)
        {
            Serilog.Log.Warning($"Failed to discard uncommitted Play edit {editId} — it expires server-side without a commit: {cleanup.Message}");
        }
    }

    /// <summary>
    /// Reads the generated Hebrew store-notes text, enforcing the store's
    /// per-language character budget before any store write. Returns null
    /// when no notes were generated for this release (pre-curation releases
    /// keep whatever the store already shows).
    /// </summary>
    static string? ReadStoreReleaseNotes(string? notesPath, int maxChars)
    {
        if (string.IsNullOrEmpty(notesPath))
        {
            return null;
        }
        var notesFile = (AbsolutePath)notesPath!;
        Assert.FileExists(notesFile, $"Store release-notes file not found: {notesFile}");
        var text = File.ReadAllText(notesFile).Trim();
        if (text.Length == 0)
        {
            return null;
        }
        Assert.True(text.Length <= maxChars,
            $"Store release notes are {text.Length} chars, over the {maxChars} per-language limit");
        return text;
    }

    /// <summary>
    /// The exact language tag Play uses for this app's Hebrew copy, read from
    /// the live listings inside the open edit — "iw" on older apps, "he" on
    /// newer ones — instead of assuming one alias everywhere.
    /// </summary>
    static string HebrewListingLanguage(AndroidPublisherService service, string editId)
    {
        var listings = service.Edits.Listings.List(GooglePlayPackageName, editId).Execute().Listings ?? [];
        return listings.FirstOrDefault(l => l.Language.StartsWith("iw") || l.Language.StartsWith("he"))?.Language ?? "iw";
    }

    /// <summary>
    /// Post-commit readback: a fresh read-only edit asks the store for the
    /// persisted track. Only a provably different value fails the deploy —
    /// the update response already proved acceptance, so an absent field or
    /// a failed read is inconclusive evidence, never a reason to mark a live
    /// bundle undelivered and re-announce its features on the next release.
    /// </summary>
    static void VerifyPlayReleaseNotes(AndroidPublisherService service, string track, long versionCode, string language, string expected)
    {
        AppEdit? verifyEdit = null;
        string? actual;
        try
        {
            verifyEdit = service.Edits.Insert(new AppEdit(), GooglePlayPackageName).Execute();
            var persisted = service.Edits.Tracks.Get(GooglePlayPackageName, verifyEdit.Id, track).Execute();
            var release = persisted.Releases?.FirstOrDefault(r => r.VersionCodes?.Contains(versionCode) == true);
            actual = release?.ReleaseNotes?.FirstOrDefault(n => n.Language == language)?.Text;
        }
        catch (Exception probe) when (probe is GoogleApiException or HttpRequestException
            or TaskCanceledException or IOException or AggregateException or InvalidOperationException)
        {
            Serilog.Log.Warning($"Hebrew release-notes readback is inconclusive — the post-commit track read failed: {probe.Message}");
            return;
        }
        finally
        {
            if (verifyEdit is not null)
            {
                try
                {
                    service.Edits.Delete(GooglePlayPackageName, verifyEdit.Id).Execute();
                }
                catch (Exception cleanup) when (cleanup is GoogleApiException or HttpRequestException
                    or TaskCanceledException or IOException or AggregateException or InvalidOperationException)
                {
                    Serilog.Log.Warning($"Failed to discard the readback edit {verifyEdit.Id}: {cleanup.Message}");
                }
            }
        }
        if (actual is null)
        {
            Serilog.Log.Warning($"Hebrew release-notes readback is inconclusive — track {track} returned no {language} releaseNotes field");
            return;
        }
        Assert.True(actual == expected,
            $"Google Play persisted different Hebrew release notes than submitted ({actual.Length} vs {expected.Length} chars)");
        Serilog.Log.Information($"Verified persisted {language} release notes on {track} track");
    }

