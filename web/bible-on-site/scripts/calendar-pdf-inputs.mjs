/**
 * Content fingerprints for calendar-PDF generation (#2608). Pure Node —
 * intentionally dependency-free so CI can compute the artifact-cache key
 * before `bun install`.
 *
 * Two scopes:
 *  - Render fingerprint (`computeCalendarPdfRenderFingerprint`): everything
 *    that can change PDF *bytes* — the renderer, bidi/layout helpers, font
 *    loaders + font binaries, the artifact/serialization logic, and the
 *    output-affecting dependency versions. A change here must re-render.
 *  - Full fingerprint (`computeCalendarPdfFingerprint`): render inputs plus
 *    every input that feeds the drawn payload — schedule/cycle data, the
 *    generated catalog, Hebrew-date logic. Used as the CI cache key so any
 *    relevant change starts a new cache lineage (restore-keys keep the
 *    previous one for partial regeneration).
 *
 * A per-artifact input sha mixes the render fingerprint with the serialized
 * drawn payload, so schedule/data changes re-render only the artifacts whose
 * content actually changed — see calendar-pdf-plan.ts.
 *
 * Usage: `node scripts/calendar-pdf-inputs.mjs [--render]` prints the
 * requested fingerprint (default: full).
 */

import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const WEBSITE_ROOT = fileURLToPath(new URL("..", import.meta.url));

/**
 * Files whose bytes can change rendered PDF output. Keep in sync with the
 * `paths:` filter of .github/workflows/calendar-pdf-publish.yml.
 */
const CALENDAR_PDF_RENDER_INPUT_FILES = [
	"src/lib/download/bidi-text.ts",
	"src/lib/download/calendar-artifacts.ts",
	"src/lib/download/calendar-pdf-plan.ts",
	"src/lib/download/calendar-pdf.ts",
	"src/lib/download/fonts/FrankRuhlLibre-Bold.ttf",
	"src/lib/download/fonts/FrankRuhlLibre-Regular.ttf",
	"src/lib/download/logo_header.jpg",
	"src/lib/download/pdf-fonts.ts",
];

/**
 * Additional inputs that feed the drawn payload (labels, schedule, bounds)
 * but not the renderer itself — a change here re-renders only the artifacts
 * whose serialized input actually differs.
 */
const CALENDAR_PDF_DATA_INPUT_FILES = [
	"scripts/calendar-pdf-inputs.mjs",
	"scripts/generate-calendar-pdfs.mts",
	"scripts/generate-client-catalog.mjs",
	"src/data/db/client-catalog.generated.json",
	"src/data/db/cycles-types.ts",
	"src/data/db/cycles.json",
	"src/data/db/cycles.ts",
	"src/data/learning-schedule.ts",
	"src/util/hebdates-util.ts",
];

export const CALENDAR_PDF_INPUT_FILES = [
	...CALENDAR_PDF_RENDER_INPUT_FILES,
	...CALENDAR_PDF_DATA_INPUT_FILES,
];

/** Dependencies whose versions can change generated bytes. */
export const CALENDAR_PDF_DEP_KEYS = [
	"@pdf-lib/fontkit",
	"bidi-js",
	"gematry",
	"pdf-lib",
	"temporal-polyfill",
];

function hashInputs(root, files, depKeys) {
	const hash = createHash("sha256");
	for (const relPath of files) {
		let bytes;
		try {
			bytes = readFileSync(join(root, relPath));
		} catch {
			// A missing generated file still fingerprints deterministically —
			// record the absence rather than silently keying an incomplete set.
			bytes = "<missing>";
		}
		hash.update(relPath);
		hash.update("\0");
		hash.update(bytes);
		hash.update("\0");
	}
	if (depKeys.length > 0) {
		const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
		for (const dep of depKeys) {
			const version = pkg.dependencies?.[dep] ?? pkg.devDependencies?.[dep];
			hash.update(`dep:${dep}=${version ?? "<absent>"}\0`);
		}
	}
	return hash.digest("hex");
}

/** Renderer+fonts+deps — mixed into every artifact's input sha. */
export function computeCalendarPdfRenderFingerprint(root = WEBSITE_ROOT) {
	return hashInputs(
		root,
		CALENDAR_PDF_RENDER_INPUT_FILES,
		CALENDAR_PDF_DEP_KEYS,
	);
}

/** Render inputs + payload data — the CI cache key / manifest fingerprint. */
export function computeCalendarPdfFingerprint(root = WEBSITE_ROOT) {
	return hashInputs(root, CALENDAR_PDF_INPUT_FILES, CALENDAR_PDF_DEP_KEYS);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const render = process.argv.includes("--render");
	const fingerprint = render
		? computeCalendarPdfRenderFingerprint()
		: computeCalendarPdfFingerprint();
	process.stdout.write(`${fingerprint}\n`);
}
