import type { Locator } from "@playwright/test";
import { expect, test } from "../util/playwright/test-fixture";

/**
 * Regression coverage for Tanahpedia footnotes (#2615).
 *
 * The e2e database seeds the production-synced legacy entries — משה רבנו
 * (55 notes) and יהושע בן נון (10) in the `#note-N`/`#noteref-N` markup
 * generation — so these tests exercise the real public entry renderer:
 * normalization → sanitization → the shipped stylesheet.
 *
 * The reported defect had two faces:
 *  1. references inside entry prose not recognizable as footnote references
 *     (a bare `<a>`), and
 *  2. the notes section showing both a native decimal marker and a baked-in
 *     Hebrew letter.
 *
 * The contract: every decorative identifier (inline reference marker, note
 * label, return glyph) is generated by CSS pseudo-elements from stable
 * `data-marker` attributes — exactly one Hebrew-letter marker per note — and
 * never lands in the article's extractable text.
 */

const MOSHE_URL = `/pedia/${encodeURIComponent("משה-רבנו")}`;
const YEHOSHUA_URL = `/pedia/${encodeURIComponent("יהושע-בן-נון")}`;

/** Computed `content` of a pseudo-element (`"none"`/`"normal"` when absent). */
async function pseudoContent(
	locator: Locator,
	pseudo: "::before" | "::after" | "::marker",
): Promise<string> {
	return locator.evaluate((el, p) => getComputedStyle(el, p).content, pseudo);
}

test.describe("Tanahpedia footnotes", () => {
	test.describe("notes list", () => {
		test("renders exactly one generated Hebrew marker per note", async ({
			page,
		}) => {
			await page.goto(MOSHE_URL);

			const list = page.locator("article ol.footnotes");
			await expect(list).toBeVisible();
			const items = list.locator(":scope > li");
			/* משה רבנו is the long entry: 55 notes, exercising single- and
			   multi-letter Hebrew numbering. */
			expect(await items.count()).toBeGreaterThan(50);

			/* No native decimal counter — list-style: none suppresses the
			   ::marker box entirely, so the only visible identifier is the
			   generated ::before below. */
			expect(
				await list.evaluate((el) => getComputedStyle(el).listStyleType),
			).toBe("none");
			expect(
				await items
					.first()
					.evaluate((el) => getComputedStyle(el).listStyleType),
			).toBe("none");

			/* Every note's ::before shows exactly its own Hebrew letter —
			   matching the inline reference — including multi-letter values. */
			const expected: Array<[string, string]> = [
				["fn:1", "א"],
				["fn:10", "י"],
				["fn:11", "יא"],
				["fn:15", "טו"],
				["fn:16", "טז"],
				["fn:54", "נד"],
			];
			for (const [id, letter] of expected) {
				const item = page.locator(`article li[id="${id}"]`);
				await expect(item).toHaveCount(1);
				expect(await item.getAttribute("data-marker")).toBe(letter);
				expect(await pseudoContent(item, "::before")).toBe(`"${letter}"`);
				/* The letter must not also be baked into the note text — that was
				   the "1. א" duplication. Note prose leads instead. */
				const text = (await item.textContent())?.trim() ?? "";
				expect(text.startsWith(letter)).toBe(false);
			}

			/* The section label is generated too — no leftover <h2>הערות</h2> or
			   <hr> furniture from the hand-made markup generation. */
			expect(await pseudoContent(list, "::before")).toBe('"הערות"');
			await expect(
				page.locator("article h1,h2,h3,h4,h5,h6", { hasText: "הערות" }),
			).toHaveCount(0);
		});

		test("keeps note markers out of the extractable article text", async ({
			page,
		}) => {
			await page.goto(MOSHE_URL);
			const items = page.locator("article ol.footnotes > li");
			const first = items.first();
			/* textContent never contains CSS-generated content: the extracted
			   text starts with the real note content, not with the marker
			   the ::before paints. */
			expect(((await first.textContent()) ?? "").trim()).toMatch(/^שמות/);
		});
	});

	test.describe("inline references", () => {
		test("renders references as compact generated superscript links", async ({
			page,
		}) => {
			await page.goto(MOSHE_URL);
			const ref = page.locator('article sup[id="fnref:1"] a.footnote-ref');
			await expect(ref).toHaveCount(1);

			/* The marker is a ::before generated from data-marker — the anchor
			   itself holds no text. */
			expect(await ref.getAttribute("data-marker")).toBe("א");
			expect(await ref.getAttribute("href")).toBe("#fn:1");
			expect(await ref.getAttribute("role")).toBe("doc-noteref");
			expect(await ref.getAttribute("aria-label")).toBe("הערה א");
			expect(await pseudoContent(ref, "::before")).toBe('"א"');
			expect((await ref.textContent()) ?? "").toBe("");

			/* Compact superscript sizing — recognizable as a footnote link. */
			const metrics = await page.locator('sup[id="fnref:1"]').evaluate((el) => {
				const cs = getComputedStyle(el);
				return { fontSize: cs.fontSize, verticalAlign: cs.verticalAlign };
			});
			expect(metrics.verticalAlign).toBe("super");
			const bodySize = await page
				.locator("article")
				.evaluate((el) => Number.parseFloat(getComputedStyle(el).fontSize));
			expect(Number.parseFloat(metrics.fontSize)).toBeLessThan(bodySize);
		});
	});

	test.describe("navigation", () => {
		test("links reference → note → back to the reference", async ({ page }) => {
			await page.goto(MOSHE_URL);
			const ref = page.getByRole("link", { name: "הערה ה", exact: true });
			await ref.click();
			await expect(page).toHaveURL(/#fn:5$/);
			const note = page.locator('article li[id="fn:5"]');
			await expect(note).toBeInViewport();

			const back = note.locator("a.footnote-backref");
			await expect(back).toHaveAttribute("href", "#fnref:5");
			await expect(back).toHaveAttribute("role", "doc-backlink");
			await back.click();
			await expect(page).toHaveURL(/#fnref:5$/);
			await expect(page.locator('sup[id="fnref:5"]')).toBeInViewport();
		});

		test("activates a reference from the keyboard", async ({ page }) => {
			await page.goto(MOSHE_URL);
			const ref = page.getByRole("link", { name: "הערה ז", exact: true });
			await ref.focus();
			await expect(ref).toBeFocused();
			await page.keyboard.press("Enter");
			await expect(page).toHaveURL(/#fn:7$/);
		});
	});

	test("generates unique footnote ids across the entry", async ({ page }) => {
		await page.goto(YEHOSHUA_URL);
		const ids = await page
			.locator("article [id]")
			.evaluateAll((els) => els.map((el) => el.id));
		expect(new Set(ids).size).toBe(ids.length);
		expect(await page.locator("article ol.footnotes > li").count()).toBe(10);
	});
});
